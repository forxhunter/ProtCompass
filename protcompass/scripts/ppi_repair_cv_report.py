"""Summarise the chain-disjoint cross-validation of scripts/ppi_repair_cv.py and set PPI affinity's status.

Per encoder, R_var and R_sham are averaged over the 15 folds (5 folds x 3 assignments). The rule is the naming rule
of Section 4.3 applied to those averages: a two-sided sign test over encoders with Holm correction over the two
properties, a mean of at least 0.02, and the same test over architecture families. The interval is a bootstrap that
resamples encoders and, inside each encoder, folds.

  python ppi_repair_cv_report.py [--latex]
  python ppi_repair_cv_report.py --random [--latex]      # the random-fold control (ppi_repair_cv.py --random-folds)
  python ppi_repair_cv_report.py --all [--latex]         # all four PPI pairs the full grid names (ppi_cv, ppi_cv_size,
                                                         # ppi_cv_shape), Holm over the four
"""
import os as _os  # release: repository root, override with the PROTCOMPASS_ROOT environment variable
PROTCOMPASS_ROOT = _os.environ.get("PROTCOMPASS_ROOT") or _os.path.abspath(
    _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "../.."))
import argparse
import glob
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import binomtest

sys.path.insert(0, str(Path(__file__).parent))
from family_weighted_demand import family, holm                         # noqa: E402
from panel import only_panel                                            # noqa: E402

ROOT = Path((PROTCOMPASS_ROOT + "/protcompass"))
FLOOR = 0.02


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--latex", action="store_true")
    ap.add_argument("--random", action="store_true", help="summarise the random-fold control")
    ap.add_argument("--all", action="store_true", help="the four PPI pairs of the full grid")
    a = ap.parse_args()
    subs, sfx = (["ppi_cv_random", "ppi_cv_random_local"], "_random") if a.random else \
        ((["ppi_cv", "ppi_cv_size", "ppi_cv_shape"], "_all") if a.all else (["ppi_cv"], ""))
    # one file per (directory group, encoder): the first complete one, local before the remote copy, so no encoder
    # mixes folds computed on two machines
    files = []
    for sub in subs:
        encs = {Path(f).stem for g in (sub, sub + "_remote", sub + "_local") for f in glob.glob(str(ROOT / "erasure" / g / "*.csv"))}
        for e in sorted(encs):
            cands = [ROOT / "erasure" / g / f"{e}.csv" for g in (sub, sub + "_local", sub + "_remote")]
            cands = [c for c in cands if c.exists()]
            full = [c for c in cands if len(pd.read_csv(c)) >= 15]
            files.append(str((full or cands)[0]))
    d = only_panel(pd.concat([pd.read_csv(f) for f in files], ignore_index=True))
    d = d.drop_duplicates(subset=["encoder", "concept", "repeat", "fold"], keep="last")
    enc = d.groupby(["concept", "encoder"])[["R_var", "R_sham", "Rperm_var", "delta_sham", "delta_var"]].mean().reset_index()
    rng = np.random.default_rng(0)
    rows = []
    for c, g in enc.groupby("concept"):
        v = g.R_var.to_numpy()
        k, n = int((v > 0).sum()), len(v)
        fam = g.assign(f=g.encoder.map(family)).groupby("f").R_var.mean()
        kf, nf = int((fam > 0).sum()), len(fam)
        cells = d[(d.concept == c) & d.R_var.notna()]          # two of the 990 fold-cells returned no score
        boot = []
        encs = g.encoder.to_numpy()
        for _ in range(2000):
            pick = rng.choice(encs, len(encs))
            m = [rng.choice(v_e := cells[cells.encoder == e].R_var.to_numpy(), len(v_e)).mean() for e in pick]
            boot.append(np.mean(m))
        rep = cells.groupby(["repeat", "encoder"]).R_var.mean().groupby("repeat").mean()
        rows.append(dict(concept=c, n=n, pos=k, R_var=float(v.mean()), lo=float(np.percentile(boot, 2.5)),
                         hi=float(np.percentile(boot, 97.5)), p=binomtest(k, n, 0.5).pvalue,
                         fam_pos=kf, fam_n=nf, fam_R=float(fam.mean()), p_fam=binomtest(kf, nf, 0.5).pvalue,
                         R_sham=float(g.R_sham.mean()), Rperm=float(g.Rperm_var.mean()),
                         delta_sham=float(g.delta_sham.mean()), delta_var=float(g.delta_var.mean()),
                         R_by_repeat=" / ".join(f"{x:+.4f}" for x in rep), folds=int(cells.groupby("encoder").size().min())))
    R = pd.DataFrame(rows)
    R["p_holm"] = holm(R.p.to_numpy())
    R["p_fam_holm"] = holm(R.p_fam.to_numpy())
    R["passes"] = (R.p_holm < 0.05) & (R.R_var >= FLOOR)
    R["passes_family"] = (R.p_fam_holm < 0.05) & (R.fam_R >= FLOOR)
    R.to_csv(ROOT / "erasure" / f"ppi_repair_cv{sfx}_summary.csv", index=False)
    if a.latex:
        print("% generated by scripts/ppi_repair_cv_report.py; do not edit by hand")
        print("\\begin{tabular}{lrrrrrr}")
        print("\\toprule")
        print("property & encoders & $R_{\\mathrm{var}}$ [95\\% CI] & Holm $p$ & families & "
              "$R_{\\mathrm{var}}$ by assignment & passes \\\\")
        print("\\midrule")
        for r in R.itertuples():
            print(f"{r.concept} & {r.pos}/{r.n} & ${r.R_var:+.4f}$ [${r.lo:+.4f}$, ${r.hi:+.4f}$] & "
                  f"${r.p_holm:.3g}$ & {r.fam_pos}/{r.fam_n} & {r.R_by_repeat} & {'yes' if r.passes else 'no'} \\\\")
        print("\\bottomrule")
        print("\\end{tabular}")
        return
    pd.set_option("display.width", 250)
    print(R.round(4).to_string(index=False))


if __name__ == "__main__":
    main()
