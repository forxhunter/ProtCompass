"""The group comparison of Section 4.2 with every representation projected to one dimension.

Reads extract/score_fixed_dim/ (extract/score2_fixed_dim.py), selects the probe per cell exactly as the released
table does (the probe with the lower mean validation loss over its three seeds, reported as the mean of that probe's
seeds), and runs the group comparisons of scripts/group_controls.py on it, beside the released numbers.

  python fixed_dim_report.py [--latex]
"""
import os as _os  # release: repository root, override with the PROTCOMPASS_ROOT environment variable
PROTCOMPASS_ROOT = _os.environ.get("PROTCOMPASS_ROOT") or _os.path.abspath(
    _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "../.."))
import argparse
import glob
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).parent))
import group_controls as G                                              # noqa: E402

ROOT = Path((PROTCOMPASS_ROOT + "/protcompass"))
FD = ROOT / "extract" / "score_fixed_dim"


def selected():
    d = pd.concat([pd.read_csv(f) for f in sorted(glob.glob(str(FD / "scores_long_*.csv")))], ignore_index=True)
    d = d.drop_duplicates(subset=["task", "encoder", "probe", "seed"], keep="last")
    pv = d.groupby(["task", "encoder", "probe"]).val_loss.mean().reset_index()
    best = pv.loc[pv.groupby(["task", "encoder"]).val_loss.idxmin(), ["task", "encoder", "probe"]]
    sel = d.merge(best, on=["task", "encoder", "probe"])
    agg = sel.groupby(["task", "encoder"]).score.agg(["mean", "std", "size"]).reset_index()
    agg = agg.rename(columns={"mean": "score", "std": "seed_sd", "size": "n_seeds"})
    agg.to_csv(FD / "selected.csv", index=False)
    return agg, d


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--latex", action="store_true")
    a = ap.parse_args()
    agg, d = selected()
    fd = G.summarize(scores=FD / "selected.csv")
    rel = G.summarize()
    rows = []
    for name in fd.restriction.unique():
        f, r = fd[fd.restriction == name], rel[rel.restriction == name]
        m = f.merge(r, on="task", suffixes=("_fd", "_rel"))
        rows.append(dict(restriction=name, n_seq=int(f.n_seq.iloc[0]), n_crd=int(f.n_crd.iloc[0]),
                         tasks=len(m), gap_rel=float(m.gap_rel.mean()), gap_fd=float(m.gap_fd.mean()),
                         leads_rel=int(m.seq_leads_rel.sum()), leads_fd=int(m.seq_leads_fd.sum()),
                         fam_sig_rel=int((m.fam_p_rel < 0.05).sum()), fam_sig_fd=int((m.fam_p_fd < 0.05).sum())))
    S = pd.DataFrame(rows)
    S.to_csv(FD / "group_summary.csv", index=False)
    fd.to_csv(FD / "group_by_task.csv", index=False)
    if a.latex:
        print("% generated by scripts/fixed_dim_report.py; do not edit by hand")
        print("\\begin{tabular}{lrrrrrr}")
        print("\\toprule")
        print(" & & \\multicolumn{2}{c}{mean gap over tasks} & \\multicolumn{2}{c}{tasks the sequence group leads} & "
              "family-clustered $p<0.05$ \\\\")
        print("\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}")
        print("restriction & encoders & released & 116 dims & released & 116 dims & 116 dims \\\\")
        print("\\midrule")
        for r in S.itertuples():
            print(f"{r.restriction} & {r.n_seq} / {r.n_crd} & ${r.gap_rel:+.3f}$ & ${r.gap_fd:+.3f}$ & "
                  f"{r.leads_rel} of {r.tasks} & {r.leads_fd} of {r.tasks} & {r.fam_sig_fd} of {r.tasks} \\\\")
        print("\\bottomrule")
        print("\\end{tabular}")
        return
    pd.set_option("display.width", 220)
    print(f"cells: {len(agg)}; tasks {agg.task.nunique()}; encoders {agg.encoder.nunique()}\n")
    print(S.round(4).to_string(index=False))
    print()
    print(fd[["restriction", "task", "gap", "fam_gap", "fam_p", "seq_leads"]].round(3).to_string(index=False))


if __name__ == "__main__":
    main()
