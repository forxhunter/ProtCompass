"""The selective-repair table, emitted from erasure/addback_rescue.csv so the manuscript cannot drift from it.

One row per task and descriptor: the mean over encoders of

    R = [ S(erased + descriptor) - S(erased) ] - mean over shams [ S(sham + descriptor) - S(sham) ]

with the count of encoders whose R is positive. The named descriptor is the property the erasure names, the permuted
one is the same columns with the proteins shuffled, and the other one is every remaining independent structural
block.

  python emit_addback_table.py [--head linear] [--latex]
"""
import os as _os  # release: repository root, override with the PROTCOMPASS_ROOT environment variable
PROTCOMPASS_ROOT = _os.environ.get("PROTCOMPASS_ROOT") or _os.path.abspath(
    _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "../.."))
import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path((PROTCOMPASS_ROOT + "/protcompass"))
sys.path.insert(0, str(ROOT / "scripts"))
from addback_rescue import contrasts                                    # noqa: E402

LABEL = {"membrane_soluble": "membrane vs soluble", "solubility": "solubility",
         "subcellular_localization": "subcellular localisation"}
DESC = {"named": "amino-acid composition (named)", "permuted": "the same, proteins permuted",
        "other": "the other structural blocks"}
ORDER = ["named", "permuted", "other"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--head", default="linear", choices=["linear", "mlp"])
    ap.add_argument("--latex", action="store_true")
    a = ap.parse_args()
    d = pd.read_csv(ROOT / "erasure" / "addback_rescue.csv")
    c = contrasts(d, a.head)
    if c.empty:
        raise SystemExit("no contrasts yet")

    rows = []
    for task, g in c.groupby("task"):
        base = g[g.descriptor == "named"]
        for q in ORDER:
            h = g[g.descriptor == q]
            if h.empty:
                continue
            rows.append(dict(task=task, descriptor=q, n=len(h), R=h.R.mean(), sd=h.R.std(),
                             n_pos=int((h.R > 0).sum()),
                             intact=base.intact.mean(), erased=base.erased.mean(), sham=base.sham_none.mean()))
    t = pd.DataFrame(rows)

    if not a.latex:
        pd.set_option("display.width", 200)
        print(t.round(4).to_string(index=False))
        return

    print("% generated by scripts/emit_addback_table.py; do not edit by hand")
    print("\\begin{tabular}{llrrrr}")
    print("\\toprule")
    print("task & descriptor added back & encoders & intact / erased / sham & mean $R$ & $R>0$ \\\\")
    print("\\midrule")
    tasks = list(t.task.unique())
    for ti, (task, g) in enumerate(t.groupby("task")):
        first = True
        for r in g.set_index("descriptor").reindex(ORDER).dropna(how="all").reset_index().itertuples():
            scores = (f"{r.intact:.3f} / {r.erased:.3f} / {r.sham:.3f}" if first else "")
            name = LABEL.get(task, task) if first else ""
            sd = f" $\\pm$ {r.sd:.3f}" if np.isfinite(r.sd) else ""
            print(f"{name} & {DESC.get(r.descriptor, r.descriptor)} & {int(r.n)} & {scores} & "
                  f"${r.R:+.4f}${sd} & {int(r.n_pos)} / {int(r.n)} \\\\")
            first = False
        if ti < len(tasks) - 1:
            print("\\midrule")
    print("\\bottomrule")
    print("\\end{tabular}")
    print(f"% head: {a.head}; scores are AUROC for the two binary tasks and accuracy for subcellular localisation")


if __name__ == "__main__":
    main()
