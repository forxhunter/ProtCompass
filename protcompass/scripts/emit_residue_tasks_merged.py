"""One per-encoder table for the two residue-resolved tasks (appendix, residue-level tasks).

Uses the loaders of residue_readout_report.py: contact AUPRC (contact_task/contact_auprc.csv) and interface AUPRC
(masif_site/results/by_source/*.csv), each with its rank among the encoders scored on that task, next to the encoder's
mean rank over the ten pooled tasks. Nothing is recomputed.

  python emit_residue_tasks_merged.py > residue_tasks.tex
"""
import numpy as np

import residue_readout_report as rr


def main():
    sc, _ = rr.scores("contact")
    si, full = rr.scores("masif")
    crd, pr = rr.audit(), rr.pooled_rank()
    rc, ri = sc.rank(ascending=False), si.rank(ascending=False)
    enc = sorted(set(sc.index) | set(si.index), key=lambda e: (pr.get(e, np.inf), e))
    print("% generated by scripts/emit_residue_tasks_merged.py from contact_task/contact_auprc.csv and")
    print("% masif_site/results/by_source/*.csv (loaders of residue_readout_report.py); do not edit by hand")
    print(r"\begingroup")
    print(r"\fontsize{7}{8.6}\selectfont")
    print(r"\setlength{\tabcolsep}{3pt}")
    print(r"\renewcommand{\arraystretch}{1.05}")
    print(r"\begin{longtable}{lcrrrrr}")
    cap = (r"\caption{The two residue-resolved tasks per encoder, two-layer readout: contact pairs (AUPRC, base rate "
           r"$0.028$, and $0.021$ for sequence separation alone) and interface residues on the 353 MaSIF-site test chains "
           r"(AUPRC, mean of three seeds, base rate $0.177$), each with the encoder's rank among those scored on the task, "
           r"next to its mean rank among the 33 encoders over the ten pooled tasks. Encoders are ordered by that mean rank. "
           r"Contact prediction has no floors, because every coordinate floor contains the label; the interface floors go "
           r"through the identical probe (\texttt{scripts/residue\_readout\_report.py}).}")
    print(cap + r"\label{tab:contact_task}\label{tab:masif_task}\\")
    head = [r"\toprule", r"\rowcolor{CompassLavender!32}",
            r" & & & \multicolumn{2}{c}{contact pairs} & \multicolumn{2}{c}{interface residues} \\",
            r"\rowcolor{CompassLavender!32}",
            r"encoder & reads coordinates & pooled rank & AUPRC & rank & AUPRC & rank \\", r"\midrule"]
    print("\n".join(head))
    print(r"\endfirsthead")
    print(r"\multicolumn{7}{l}{\small\textit{Table \thetable{} (continued)}}\\")
    print("\n".join(head))
    print(r"\endhead")
    print(r"\midrule")
    print(r"\endfoot")
    print(r"\bottomrule")
    print(r"\endlastfoot")

    def cell(s, r, e):
        return (f"${s[e]:.3f}$", str(int(r[e]))) if e in s.index else ("--", "")

    for e in enc:
        c, i = cell(sc, rc, e), cell(si, ri, e)
        p = f"${pr[e]:.1f}$" if e in pr.index and np.isfinite(pr[e]) else "--"
        print(f"{rr.DISP.get(e, e)} & {'yes' if crd.get(e, False) else 'no'} & {p} & {c[0]} & {c[1]} & {i[0]} & {i[1]} \\\\")
    print(r"\midrule")
    for f in rr.ALL_FLOORS:
        if f in full.index:
            print(f"\\texttt{{{f.replace('_', chr(92) + '_')}}} & floor & & -- & & ${full.loc[f, 'auprc']:.3f}$ & \\\\")
    print(r"\end{longtable}")
    print(r"\endgroup")


if __name__ == "__main__":
    main()
