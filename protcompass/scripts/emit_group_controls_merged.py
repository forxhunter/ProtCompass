"""One table for the downstream group comparison under each restriction (appendix, downstream controls).

Merges what group_controls.py, group_controls_multiplicity.py and fixed_dim_report.py report for the same three
restrictions, from their released CSVs; nothing is recomputed.

  python emit_group_controls_merged.py      writes extract/group_controls_merged.tex
"""
import os as _os  # release: repository root, override with the PROTCOMPASS_ROOT environment variable
PROTCOMPASS_ROOT = _os.environ.get("PROTCOMPASS_ROOT") or _os.path.abspath(
    _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "../.."))
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path((PROTCOMPASS_ROOT + "/protcompass"))
M = pd.read_csv(ROOT / "extract" / "group_controls_multiplicity.csv").set_index("restriction")
F = pd.read_csv(ROOT / "extract" / "score_fixed_dim" / "group_summary.csv").set_index("restriction")
assert list(M.index) == list(F.index)
for r in M.index:  # the columns the two sources share must agree
    assert (M.loc[r, "n_seq"], M.loc[r, "n_crd"]) == (F.loc[r, "n_seq"], F.loc[r, "n_crd"]), r
    assert M.loc[r, "tasks_seq_leads"] == F.loc[r, "leads_rel"] and M.loc[r, "tasks_p05"] == F.loc[r, "fam_sig_rel"], r
    assert np.isclose(M.loc[r, "mean_raw_gap"], F.loc[r, "gap_rel"]), r


def gap(x):
    return f"${x:+.3f}$"


def pval(p):
    return "$<0.001$" if p < 0.001 else f"{p:.3f}"


L = ["% generated by scripts/emit_group_controls_merged.py from extract/group_controls_multiplicity.csv and",
     "% extract/score_fixed_dim/group_summary.csv; do not edit by hand",
     r"\begin{adjustbox}{max width=\linewidth}",
     r"\begin{tabular}{lcccccccc}", r"\toprule", r"\rowcolor{CompassLavender!32}",
     r" & & & \multicolumn{2}{c}{tasks the sequence group leads} & \multicolumn{2}{c}{mean gap over tasks} & "
     r"\multicolumn{2}{c}{tasks, family test $p<0.05$} \\",
     r"\rowcolor{CompassLavender!32}",
     r"restriction & encoders & families & native & 116 dims & native & 116 dims & native & 116 dims \\",
     r"\midrule"]
INT = ["n_seq", "n_crd", "fam_seq", "fam_crd", "tasks_seq_leads", "tasks", "tasks_p05", "tasks_holm05",
       "leads_fd", "fam_sig_fd"]
M[[c for c in INT if c in M]] = M[[c for c in INT if c in M]].astype(int)
F[[c for c in INT if c in F]] = F[[c for c in INT if c in F]].astype(int)
for r in M.index:
    m, f = M.loc[r].to_dict(), F.loc[r].to_dict()
    m = type("R", (), {k: (int(v) if k in INT else v) for k, v in m.items()})
    f = type("R", (), {k: (int(v) if k in INT else v) for k, v in f.items()})
    L.append(f"{r} & {m.n_seq} / {m.n_crd} & {m.fam_seq} / {m.fam_crd} & {m.tasks_seq_leads} of {m.tasks} & "
             f"{f.leads_fd} of {f.tasks} & {gap(m.mean_raw_gap)} & {gap(f.gap_fd)} & {m.tasks_p05} of {m.tasks} & "
             f"{f.fam_sig_fd} of {f.tasks} \\\\")
L += [r"\midrule", r"\rowcolor{CompassLavender!32}",
      r"restriction & \multicolumn{2}{c}{tasks after Holm} & \multicolumn{3}{c}{mean rank gap (permutation $p$)} & "
      r"\multicolumn{3}{c}{normalised gap} \\", r"\midrule"]
for r in M.index:
    m = type("R", (), {k: (int(v) if k in INT else v) for k, v in M.loc[r].to_dict().items()})
    L.append(f"{r} & \\multicolumn{{2}}{{c}}{{{m.tasks_holm05} of {m.tasks}}} & "
             f"\\multicolumn{{3}}{{c}}{{${m.fam_rank_gap:+.1f}$ ({pval(m.fam_rank_gap_p)})}} & "
             f"\\multicolumn{{3}}{{c}}{{{gap(m.norm_gap)}}} \\\\")
L += [r"\bottomrule", r"\end{tabular}", r"\end{adjustbox}", ""]
out = ROOT / "extract" / "group_controls_merged.tex"
out.write_text("\n".join(L))
print("wrote", out)
