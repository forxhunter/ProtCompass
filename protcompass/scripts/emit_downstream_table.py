"""The full downstream matrix and its seed standard deviations, generated from the released scores.

The hand-written version of this table had nine task columns while the release scores ten, so membrane/soluble --
a task the interventional section uses -- had no per-encoder row anywhere in the paper, and the group means quoted
over ten tasks came from a table showing nine. Generating it removes that class of error.

  python emit_downstream_table.py scores | sd
"""
import os as _os  # release: repository root, override with the PROTCOMPASS_ROOT environment variable
PROTCOMPASS_ROOT = _os.environ.get("PROTCOMPASS_ROOT") or _os.path.abspath(
    _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "../.."))
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path((PROTCOMPASS_ROOT + "/protcompass"))
sys.path.insert(0, str(ROOT / "scripts"))
from make_panels_original_style import DISP  # noqa: E402

ORDER = ["ec_classification", "remote_homology", "subcellular_localization", "go_mf", "go_bp",
         "solubility", "membrane_soluble", "fluorescence", "stability", "ppi_affinity"]
HEAD = ["EC", "R.Hom.", "Subcell.", "GO-MF", "GO-BP", "Solub.", "Memb.", "Fluor.", "Stab.", "PPI Aff."]
METRIC = ["Acc.", "Acc.", "Acc.", "F-max", "F-max", "AUROC", "AUROC", "Sp.", "Sp.", "Sp."]
REF = "ref_composition"


def load(value):
    d = pd.read_csv(ROOT / "extract" / "scores2_selected.csv")
    w = d.pivot(index="encoder", columns="task", values=value).reindex(columns=ORDER)
    a = pd.read_csv(ROOT / "extract" / "encoder_input_audit.csv").drop_duplicates("encoder").set_index("encoder")
    uses = a.uses_coordinates.astype(bool).reindex(w.index)
    return w, uses


def table(value, digits=3):
    w, uses = load(value)
    score, _ = load("score")
    rank = score.drop(index=REF, errors="ignore").rank(ascending=False).mean(axis=1)
    best = score.drop(index=REF, errors="ignore").max()
    out = []
    print("% generated by scripts/emit_downstream_table.py; do not edit by hand")
    print("\\begin{tabular}{l" + "r" * (len(ORDER) + 1) + "}")
    print("\\toprule")
    print("\\textbf{Encoder} & " + " & ".join(f"\\textbf{{{h}}}" for h in HEAD) + " & \\textbf{MR} \\\\")
    print(" & " + " & ".join(f"\\textit{{{m}}}" for m in METRIC) + " & \\\\")
    print("\\midrule")
    seq_mask = ~uses.fillna(True).astype(bool)
    for label, mask in (("Measured to read sequence only", seq_mask),
                        ("Measured to read coordinates", ~seq_mask)):
        idx = [e for e in rank[mask.reindex(rank.index).fillna(False)].sort_values().index]
        print(f"\\multicolumn{{{len(ORDER) + 2}}}{{l}}{{\\textit{{{label} ({len(idx)} encoders)}}}} \\\\")
        for e in idx:
            cells = []
            for t in ORDER:
                v = w.loc[e, t]
                if not np.isfinite(v):
                    cells.append("--")
                elif value == "score" and np.isclose(v, best[t]):
                    cells.append(f"\\textbf{{{v:.{digits}f}}}")
                else:
                    cells.append(f"{v:.{digits}f}")
            print(f"{DISP.get(e, e)} & " + " & ".join(cells) + f" & {rank[e]:.1f} \\\\")
    if REF in w.index:
        print("\\midrule")
        cells = [("--" if not np.isfinite(w.loc[REF, t]) else f"{w.loc[REF, t]:.{digits}f}") for t in ORDER]
        print("\\textit{composition reference} & " + " & ".join(cells) + " & -- \\\\")
    print("\\bottomrule")
    print("\\end{tabular}")
    print(f"% {len(w.drop(index=REF, errors='ignore'))} encoders x {len(ORDER)} tasks")


if __name__ == "__main__":
    table("score") if sys.argv[1] == "scores" else table("seed_sd", digits=4)
