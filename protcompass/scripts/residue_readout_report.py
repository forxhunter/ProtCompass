"""Group comparison and ranking transfer for the two residue-resolved readouts: the contact task
(contact_task/contact_auprc.csv, scripts/t8_contact_task.py) and the interface task (masif_site/results,
scripts/masif_interface_probe.py).

For each encoder the score is AUPRC under the two-layer readout (mean over its seeds). Encoders are grouped by the
measured input audit (uses_coordinates). Reported: the group means with a one-sided Mann-Whitney test (coordinate
group larger), the Spearman correlation between the score and the encoder's mean rank over the ten pooled tasks of
Section 4.2 (extract/scores2_wide.csv; rank 1 is best), the encoders that move most between the two rankings, and for
the interface task the best floor of each kind through the same readout.

  python residue_readout_report.py contact|masif [--latex]
"""
import os as _os  # release: repository root, override with the PROTCOMPASS_ROOT environment variable
PROTCOMPASS_ROOT = _os.environ.get("PROTCOMPASS_ROOT") or _os.path.abspath(
    _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "../.."))
import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import mannwhitneyu, spearmanr

ROOT = Path((PROTCOMPASS_ROOT + "/protcompass"))
sys.path.insert(0, str(ROOT / "scripts"))
from panel import panel                                                 # noqa: E402
from floor_rules import SEQ_FLOORS, ALL_FLOORS                          # noqa: E402
from make_panels_original_style import DISP                              # noqa: E402


def pooled_rank():
    w = pd.read_csv(ROOT / "extract" / "scores2_wide.csv", index_col=0)
    w = w.loc[[e for e in w.index if e in panel()]]
    return w.rank(ascending=False).mean(1)


def audit():
    a = pd.read_csv(ROOT / "extract" / "encoder_input_audit.csv")
    a = a.assign(o=a.dataset.ne("probing")).sort_values("o").drop_duplicates("encoder").set_index("encoder")
    return a.uses_coordinates.astype(bool)


def scores(task):
    if task == "contact":
        d = pd.read_csv(ROOT / "contact_task" / "contact_auprc.csv")
        s = d[d.readout == "mlp2"].set_index("encoder").auprc
        return s[[e for e in s.index if e in panel()]], None
    d = pd.concat([pd.read_csv(f) for f in (ROOT / "masif_site" / "results" / "by_source").glob("*.csv")])
    m = d[d.readout == "mlp2"].groupby("source")[["auprc", "auroc"]].mean()
    enc = m.loc[[e for e in m.index if e in panel()]]
    return enc.auprc, m


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("task", choices=["contact", "masif"])
    ap.add_argument("--latex", action="store_true")
    a = ap.parse_args()
    s, full = scores(a.task)
    crd = audit()
    pr = pooled_rank()
    g = pd.DataFrame({"score": s, "coordinates": crd.reindex(s.index), "pooled_rank": pr.reindex(s.index)})
    g["rank_here"] = g.score.rank(ascending=False)
    both = g.dropna(subset=["pooled_rank"])
    both = both.assign(move=lambda x: x.pooled_rank - x.rank_here)   # places gained: pooled mean rank minus rank here
    c, q = g[g.coordinates].score, g[~g.coordinates].score
    mw = mannwhitneyu(c, q, alternative="greater")
    rho = spearmanr(both.score, both.pooled_rank)
    out = dict(task=a.task, n_crd=len(c), mean_crd=c.mean(), n_seq=len(q), mean_seq=q.mean(), mw_p=mw.pvalue,
               n_both=len(both), rho=-rho.correlation, rho_p=rho.pvalue)
    if full is not None:
        fl = full.auprc
        out.update(best_seq_floor=fl[[f for f in SEQ_FLOORS if f in fl.index]].max(),
                   best_floor=fl[[f for f in ALL_FLOORS if f in fl.index]].max(),
                   which_floor=fl[[f for f in ALL_FLOORS if f in fl.index]].idxmax(),
                   seq_above=int((q > fl[[f for f in SEQ_FLOORS if f in fl.index]].max()).sum()),
                   crd_above=int((c > fl[[f for f in ALL_FLOORS if f in fl.index]].max()).sum()))
    pd.Series(out).to_csv(ROOT / ("contact_task" if a.task == "contact" else "masif_site") / f"{a.task}_group_summary.csv")
    if a.latex:
        print(f"% generated by scripts/residue_readout_report.py {a.task}; do not edit by hand")
        print("\\begin{tabular}{lrrrr}")
        print("\\toprule")
        print(f"encoder & reads coordinates & {'contact' if a.task == 'contact' else 'interface'} AUPRC & rank here & "
              "mean rank, ten pooled tasks \\\\")
        print("\\midrule")
        order = g.sort_values("score", ascending=False)
        if a.task == "contact":          # the eight highest, then the five that fall furthest from the pooled ranking
            falls = both.sort_values("move").head(5).index
            blocks = [order.head(8), order.loc[[e for e in falls if e not in order.head(8).index]]]
        else:
            blocks = [order]
        for k, block in enumerate(blocks):
            if k:
                print("\\midrule")
            for e, r in block.iterrows():
                prs = f"${r.pooled_rank:.1f}$" if np.isfinite(r.pooled_rank) else "--"
                print(f"{DISP.get(e, e)} & {'yes' if r.coordinates else 'no'} & ${r.score:.3f}$ & {int(r.rank_here)} & {prs} \\\\")
        if full is not None:
            print("\\midrule")
            for f in ALL_FLOORS:
                if f in full.index:
                    print(f"\\texttt{{{f.replace('_', chr(92) + '_')}}} & floor & ${full.loc[f, 'auprc']:.3f}$ & & \\\\")
        print("\\bottomrule")
        print("\\end{tabular}")
        print(f"% {a.task}: coordinate mean {out['mean_crd']:.4f} (n={out['n_crd']}) against sequence-only "
              f"{out['mean_seq']:.4f} (n={out['n_seq']}), Mann-Whitney one-sided p={out['mw_p']:.2f}; Spearman with "
              f"pooled standing rho={out['rho']:+.3f}, p={out['rho_p']:.2g}; mean ranks over the 33 panel encoders")
        return
    for k, v in out.items():
        print(f"{k:16s} {v}")
    print("\nlargest rises (pooled -> here):")
    print(both.sort_values("move", ascending=False).head(7)[["score", "coordinates", "rank_here", "move"]].round(3).to_string())
    print("largest falls:")
    print(both.sort_values("move").head(5)[["score", "coordinates", "move"]].round(3).to_string())


if __name__ == "__main__":
    main()
