"""Is the sequence-vs-coordinate ordering a function of the training budget?

The stage-1 manifests cap training at 6{,}000 proteins, and a frozen-embedding shallow head at that budget may
favour whichever representations have the better-conditioned global features. Re-extracting 33 encoders on the full
splits is not affordable, so the budget is varied downward instead: the same protocol at 25%, 50% and 100% of the
training rows. If the group gap is flat over a fourfold change in budget, the ordering is not a property of the
budget over the range we can vary; if it grows as the budget shrinks, the published comparison is partly a low-data
effect and must be reported that way.

Reads the part files `extract/score_parts/scores2_long_*__frac*.csv` written by `score2.py --train-frac`.

  python train_size_sweep.py [--markdown]
"""
import os as _os  # release: repository root, override with the PROTCOMPASS_ROOT environment variable
PROTCOMPASS_ROOT = _os.environ.get("PROTCOMPASS_ROOT") or _os.path.abspath(
    _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "../.."))
import argparse
import re
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path((PROTCOMPASS_ROOT + "/protcompass"))
PARTS = ROOT / "extract" / "score_parts"
sys.path.insert(0, str(ROOT / "scripts"))
from make_panels_original_style import DECLARED  # noqa: E402
from group_controls import meta as _meta  # noqa: E402
GROUP = _meta().group

LABEL = {"ec_classification": "EC", "go_mf": "GO-MF", "go_bp": "GO-BP",
         "subcellular_localization": "localisation", "remote_homology": "homology", "solubility": "solubility",
         "stability": "stability", "fluorescence": "fluorescence", "ppi_affinity": "affinity",
         "membrane_soluble": "membrane"}


def selected(d):
    """Same rule as the released tables: pick the probe on mean validation loss, then average its seeds."""
    pv = d.groupby(["task", "encoder", "probe"]).val_loss.mean().reset_index()
    best = pv.loc[pv.groupby(["task", "encoder"]).val_loss.idxmin(), ["task", "encoder", "probe"]]
    return d.merge(best, on=["task", "encoder", "probe"]).groupby(["task", "encoder"]).score.mean()


def load():
    frames = []
    for f in sorted(PARTS.glob("scores2_long_*.csv")):
        try:
            d = pd.read_csv(f)
        except Exception:
            continue
        if "train_frac" not in d:
            d["train_frac"] = 1.0
        d["train_frac"] = d.train_frac.fillna(1.0)
        frames.append(d)
    d = pd.concat(frames, ignore_index=True)
    return d[d.encoder != "ref_composition"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--markdown", action="store_true")
    a = ap.parse_args()
    d = load()
    rows = []
    for frac, g in d.groupby("train_frac"):
        s = selected(g).reset_index()
        s["group"] = [GROUP.get(e, "coordinate-side") for e in s.encoder]  # measured audit grouping
        for task, h in s.groupby("task"):
            a_, b_ = h.score[h.group == "sequence"], h.score[h.group == "coordinate-side"]
            if len(a_) < 2 or len(b_) < 2:
                continue
            rows.append(dict(frac=frac, task=LABEL.get(task, task), seq=a_.mean(), crd=b_.mean(),
                             gap=a_.mean() - b_.mean(), n_train=int(h.attrs.get("n", 0))))
    t = pd.DataFrame(rows)
    piv = t.pivot(index="task", columns="frac", values="gap")
    if a.markdown:
        print("<!-- generated by scripts/train_size_sweep.py; do not edit by hand -->\n")
        print("| task | gap at 25% of the training rows | at 50% | at 100% |")
        print("|---|---|---|---|")
        for task, r in piv.iterrows():
            print(f"| {task} | " + " | ".join(f"{r[c]:+.3f}" for c in piv.columns) + " |")
        d25, d100 = piv[piv.columns.min()], piv[piv.columns.max()]
        print(f"\nThe group gap is the mean over the sequence group minus the mean over the coordinate side. "
              f"Over a fourfold change in the training budget the gap changes by a mean of "
              f"{(d100 - d25).abs().mean():.3f} and keeps its sign on {int((np.sign(d25) == np.sign(d100)).sum())} "
              f"of {len(piv)} tasks. The budget cannot be raised above the stage-1 cap without re-extraction, so "
              f"this bounds the budget dependence from below rather than settling it.")
        return
    print(piv.round(3).to_string())
    d25, d100 = piv[piv.columns.min()], piv[piv.columns.max()]
    print(f"\nmean |gap(100%) - gap(25%)| = {(d100 - d25).abs().mean():.3f}; "
          f"sign preserved on {int((np.sign(d25) == np.sign(d100)).sum())} of {len(piv)} tasks")


if __name__ == "__main__":
    main()
