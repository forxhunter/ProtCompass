"""LaTeX tables and figure for the pretrained-versus-random pair analysis (scripts/ab_train_pairs.py).

  python ab_train_pairs_report.py
Output: symmetric/ab_train_pairs/train_pairs.tex (summary), train_pairs_matrix.tex, train_pairs_downstream.tex,
train_pairs.png
"""
import os as _os  # release: repository root, override with the PROTCOMPASS_ROOT environment variable
PROTCOMPASS_ROOT = _os.environ.get("PROTCOMPASS_ROOT") or _os.path.abspath(
    _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "../.."))
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt                                          # noqa: E402
import numpy as np                                                       # noqa: E402
import pandas as pd                                                      # noqa: E402

ROOT = Path((PROTCOMPASS_ROOT + "/protcompass"))
OUT = ROOT / "symmetric" / "ab_train_pairs"
PRIMARY = ["GCPNet", "GearNet", "IPA", "TFN", "PottsMPNN"]
MATRIX = PRIMARY + ["PottsMPNN-soluble", "PottsMPNN-ft"]
SHORT = {"PottsMPNN-soluble": "Potts-sol", "PottsMPNN-ft": "Potts-ft", "PottsMPNN": "PottsMPNN",
         "GCPNet-vframe": "GCPNet-vf"}
PROBE_LABEL = {
    "phi_circular": r"$\phi$", "psi_circular": r"$\psi$", "local_curvature": "curvature", "dssp_3": "DSSP-3",
    "dssp_8": "DSSP-8", "core_surface": "core/surface", "contact_density": "contact density",
    "distance_bins": "distance bins", "contact_order_len_resid": "contact order",
    "radius_of_gyration_len_resid": "radius of gyration", "asphericity_len_resid": "asphericity", "rsa": "RSA",
    "rsa_bins": "RSA bins", "bfactor": "B-factor", "architecture_label": "CATH architecture",
}
PROBE_PLAIN = {k: v.replace(r"$\phi$", "phi").replace(r"$\psi$", "psi") for k, v in PROBE_LABEL.items()}
TASK_LABEL = {"ec_classification": "EC", "fluorescence": "Fluorescence", "go_bp": "GO-BP", "go_mf": "GO-MF",
              "membrane_soluble": "Membrane/soluble", "ppi_affinity": "PPI affinity",
              "remote_homology": "Remote homology", "solubility": "Solubility", "stability": "Stability",
              "subcellular_localization": "Subcellular loc."}


def fmt(x, nd=3):
    return f"{x:+.{nd}f}".replace("-", "$-$") if np.isfinite(x) else "--"


def tex(D, P, DD):
    L = []
    L.append("% Generated by scripts/ab_train_pairs_report.py from symmetric/ab_train_pairs/*.csv. Do not edit.")
    L.append("% Requires \\usepackage{booktabs}.")
    # ---------------------------------------------------------------- summary
    L += [r"\begin{table}[t]", r"\centering", r"\footnotesize", r"\setlength{\tabcolsep}{4pt}",
          r"\caption{Pretrained minus randomly initialised version of the same architecture on the fifteen probes of "
          r"the admissible floor comparison (superfamily split). A probe counts as raised or lowered when the "
          r"protein-level paired 95\% bootstrap interval (2,000 draws) of the difference lies entirely above or "
          r"below zero. Below floor: determined-label cells (of 11) whose 95\% interval against the input-matched "
          r"floor lies below zero, for the random and the pretrained version. Median $\Delta$: over the fifteen probes.}",
          r"\label{tab:train_pairs_summary}",
          r"\begin{tabular}{lccccc}", r"\toprule",
          r" & \multicolumn{3}{c}{Probes (of 15)} & & \\",
          r"\cmidrule(lr){2-4}",
          r"Pair (random $\to$ pretrained) & raised & lowered & unresolved & below floor & median $\Delta$ \\",
          r"\midrule"]
    for _, r in P.iterrows():
        if r.pair == "PottsMPNN-soluble":
            L.append(r"\midrule")
        L.append(f"{r.pair} & {r.all_increase} ({r.det_increase}) & {r.all_decrease} ({r.det_decrease}) & "
                 f"{r.all_unresolved} & {r.random_below_floor} $\\to$ {r.pretrained_below_floor} & "
                 f"{fmt(r.median_delta_all)} \\\\")
    L += [r"\bottomrule", r"\end{tabular}",
          r"\par\smallskip\footnotesize Numbers in parentheses: of which determined labels (11). GearNet pairs a "
          r"7M random configuration with the 20M pretrained model. PottsMPNN-soluble, PottsMPNN-ft and "
          r"GCPNet-vframe (frame-projected re-extraction) are secondary pairs.",
          r"\end{table}", ""]
    n_summary = len(L)
    # ---------------------------------------------------------------- per-probe matrix
    cols = [c for c in MATRIX if c in set(D.pair)]
    L += [r"\begin{table}[t]", r"\centering", r"\footnotesize", r"\setlength{\tabcolsep}{2.5pt}",
          r"\caption{Per-probe difference, pretrained minus random test score (circular cosine for $\phi$ and "
          r"$\psi$, Pearson $r$ for regression probes, balanced accuracy for classification probes). "
          r"$\uparrow$ / $\downarrow$: paired 95\% bootstrap interval entirely above / below zero.}",
          r"\label{tab:train_pairs_matrix}",
          r"\begin{tabular}{l" + "r" * len(cols) + "}", r"\toprule",
          "Probe & " + " & ".join(SHORT.get(c, c) for c in cols) + r" \\", r"\midrule"]
    probes = list(dict.fromkeys(D.probe))
    for i, p in enumerate(probes):
        if i == 11:
            L.append(r"\midrule")
        cells = []
        for c in cols:
            r = D[(D.pair == c) & (D.probe == p)]
            if not len(r):
                cells.append("--")
                continue
            r = r.iloc[0]
            mark = r"$^{\uparrow}$" if r.state == "increase" else r"$^{\downarrow}$" if r.state == "decrease" else \
                r"$^{\ast}$" if r.state == "no_interval" else r"\phantom{$^{\uparrow}$}"
            cells.append(fmt(r.delta, 3) + mark)
        L.append(PROBE_LABEL[p] + " & " + " & ".join(cells) + r" \\")
    L += [r"\bottomrule", r"\end{tabular}",
          r"\par\smallskip\footnotesize Rows above the rule: determined labels; below: undetermined labels.",
          r"\end{table}", ""]
    n_matrix = len(L)
    # ---------------------------------------------------------------- downstream
    dcols = [c for c in MATRIX if c in set(DD.pair)]
    L += [r"\begin{table}[t]", r"\centering", r"\footnotesize", r"\setlength{\tabcolsep}{2.5pt}",
          r"\caption{Downstream tasks: pretrained minus random score (three-seed mean of the validation-selected "
          r"readout). No per-protein downstream predictions are saved for the random encoders, so no test-set "
          r"interval is available. $^{+}$ / $^{-}$: the difference exceeds twice the standard error of the "
          r"difference of the two three-seed means; this reflects readout-seed variation only.}",
          r"\label{tab:train_pairs_downstream}",
          r"\begin{tabular}{l" + "r" * len(dcols) + "}", r"\toprule",
          "Task & " + " & ".join(SHORT.get(c, c) for c in dcols) + r" \\", r"\midrule"]
    for t in sorted(DD.task.unique()):
        cells = []
        for c in dcols:
            r = DD[(DD.pair == c) & (DD.task == t)]
            if not len(r) or not np.isfinite(r.iloc[0].get("delta", np.nan)):
                cells.append("--")
                continue
            r = r.iloc[0]
            mark = r"$^{+}$" if r.seed_flag == "higher" else r"$^{-}$" if r.seed_flag == "lower" else \
                r"\phantom{$^{+}$}"
            cells.append(fmt(r.delta, 3) + mark)
        L.append(TASK_LABEL.get(t, t) + " & " + " & ".join(cells) + r" \\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    # one file per table: the paper prints the summary; the matrix and the downstream table are released
    head = L[:2]
    (OUT / "train_pairs.tex").write_text("\n".join(L[:n_summary]))
    (OUT / "train_pairs_matrix.tex").write_text("\n".join(head + L[n_summary:n_matrix]))
    (OUT / "train_pairs_downstream.tex").write_text("\n".join(head + L[n_matrix:]))


def figure(D):
    BLUE, ORANGE, GRAY = "#2a78d6", "#eb6834", "#8a8984"
    INK, INK2 = "#0b0b0b", "#52514e"
    probes = list(dict.fromkeys(D.probe))
    y = np.arange(len(probes))[::-1].astype(float)
    y[11:] -= 0.6                                    # gap between determined and undetermined labels
    fig, axes = plt.subplots(1, len(PRIMARY), figsize=(13.5, 5.6), sharey=True, sharex=True)
    for ax, pair in zip(axes, PRIMARY):
        g = D[D.pair == pair].set_index("probe").loc[probes]
        for yi, (_, r) in zip(y, g.iterrows()):
            ax.plot([r.random_test, r.pretrained_test], [yi, yi], color="#c3c2b7", lw=1.5, zorder=1,
                    solid_capstyle="round")
            ax.scatter(r.random_floor_test, yi, marker="D", s=26, color=GRAY, zorder=2, linewidths=0)
            ax.scatter(r.random_test, yi, marker="o", s=44, facecolors="white", edgecolors=ORANGE, linewidths=1.6,
                       zorder=3)
            ax.scatter(r.pretrained_test, yi, marker="o", s=44, color=BLUE, zorder=4, edgecolors="white",
                       linewidths=0.8)
            tag = "↑" if r.state == "increase" else "↓" if r.state == "decrease" else ""
            if tag:
                ax.text(1.07, yi, tag, transform=ax.get_yaxis_transform(), va="center", ha="left",
                        fontsize=10, color=INK2)
        gn = g.loc[g.determined]
        nb_r = int((gn.random_floor_state == "below").sum())
        nb_p = int((gn.pretrained_floor_state == "below").sum())
        ttl = pair if pair != "GearNet" else "GearNet (7M vs 20M)"
        ax.set_title(f"{ttl}\nbelow floor {nb_r} → {nb_p} of 11", fontsize=10, color=INK, loc="left")
        ax.set_xlim(-0.05, 1.02)
        ax.grid(axis="x", color="#e6e5e0", lw=0.6)
        ax.set_axisbelow(True)
        for s in ("top", "right"):
            ax.spines[s].set_visible(False)
        for s in ("left", "bottom"):
            ax.spines[s].set_color("#c3c2b7")
        ax.tick_params(colors=INK2, labelsize=9)
        ax.axhline((y[10] + y[11]) / 2, color="#c3c2b7", lw=0.6, ls=(0, (2, 2)))
        ax.set_xlabel("test score", fontsize=9, color=INK2)
    axes[0].set_yticks(y)
    axes[0].set_yticklabels([PROBE_PLAIN[p] for p in probes], fontsize=9, color=INK)
    h = [plt.Line2D([], [], marker="D", ls="", color=GRAY, ms=5, label="input-matched floor (same for both versions)"),
         plt.Line2D([], [], marker="o", ls="", mfc="white", mec=ORANGE, mew=1.6, ms=7, label="random init"),
         plt.Line2D([], [], marker="o", ls="", color=BLUE, ms=7, label="pretrained"),
         plt.Line2D([], [], ls="", marker="$↑↓$", color=INK2, ms=12,
                    label="paired 95% interval excludes zero")]
    fig.legend(handles=h, loc="lower center", ncol=4, frameon=False, fontsize=9, bbox_to_anchor=(0.5, -0.01))
    fig.tight_layout(rect=(0, 0.05, 1, 1))
    fig.savefig(OUT / "train_pairs.png", dpi=200, facecolor="white")


def main():
    D = pd.read_csv(OUT / "probing_cells.csv")
    P = pd.read_csv(OUT / "probing_summary.csv")
    DD = pd.read_csv(OUT / "downstream.csv")
    tex(D, P, DD)
    figure(D)
    print("wrote", OUT / "train_pairs.tex", OUT / "train_pairs.png")


if __name__ == "__main__":
    main()
