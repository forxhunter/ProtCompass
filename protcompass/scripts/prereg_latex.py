"""LaTeX table of the pre-registered determinacy test: per label and determinacy status, the cells, the cells at or
below the floor, the mean G_ref over cells and over family units. Reads prereg/cells.csv (and cells_cohortB.csv when
present) written by prereg_decide.py.

  python prereg_latex.py > generated/prereg_cells.tex
"""
import os as _os  # release: repository root, override with the PROTCOMPASS_ROOT environment variable
PROTCOMPASS_ROOT = _os.environ.get("PROTCOMPASS_ROOT") or _os.path.abspath(
    _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "../.."))
from pathlib import Path

import pandas as pd

ROOT = Path((PROTCOMPASS_ROOT + "/protcompass"))
NAME = {"hbond_count": "backbone H-bond count", "chi1_class": "$\\chi_1$ class", "chi2_class": "$\\chi_2$ class",
        "ca_dihedral": "C$\\alpha$ virtual dihedral (control)", "sc_contacts": "side-chain contacts (descriptive)"}
ST = {"determined": "determined", "undetermined": "not determined", "not_established": "not established"}
C = pd.read_csv(ROOT / "prereg" / "cells.csv")
U = pd.read_csv(ROOT / "prereg" / "units.csv")
B = pd.read_csv(ROOT / "prereg" / "cells_cohortB.csv") if (ROOT / "prereg" / "cells_cohortB.csv").exists() else None
print("% generated by scripts/prereg_latex.py; do not edit by hand")
print("\\begin{tabular}{llrrrr" + ("rr" if B is not None else "") + "}")
print("\\toprule")
head = "label & status & cells & at or below floor & mean $G_{\\mathrm{ref}}$ & family units at or below"
if B is not None:
    head += " & cohort B cells & at or below"
print(head + " \\\\")
print("\\midrule")
for lab in NAME:
    for st in ("determined", "undetermined", "not_established"):
        g = C[(C.label == lab) & (C.status == st)]
        if not len(g):
            continue
        u = U[(U.label == lab) & (U.status == st)]
        ucol = f"{int((u.G_ref <= 0).sum())} of {len(u)}" if len(u) else "--"
        row = f"{NAME[lab]} & {ST[st]} & {len(g)} & {int((g.G_ref <= 0).sum())} & ${g.G_ref.mean():+.3f}$ & {ucol}"
        if B is not None:
            b = B[(B.label == lab) & (B.status == st)]
            row += f" & {len(b)} & {int((b.G_ref <= 0).sum())}" if len(b) else " & -- & --"
        print(row + " \\\\")
print("\\bottomrule")
print("\\end{tabular}")
