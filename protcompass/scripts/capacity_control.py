"""Is the floor comparison a comparison of capacity rather than of information?

A fixed descriptor and an embedding are read by the same probe, so whichever is wider and better conditioned has an
advantage that has nothing to do with what it carries. The floors run from 2 to 357 features and the embeddings
from 20 to 2560, so the objection is live. Three views of the released runs, none of which needs a new probe:

  width curve        probe score against log width, over all 41 sources, per probe. If width drove the result the
                     floors would sit on the same curve as the encoders and above them only where they are wider.
  width-residual     the floor-minus-encoder gap after regressing log width out of the scores, per probe. This
                     asks whether the floor still leads a comparison in which both sides are given the width they
                     have rather than the width they need.
  matched pairs      the same comparison restricted to (floor, encoder) pairs whose widths are within a factor of
                     two, which needs no model at all.

  python capacity_control.py [--markdown]
"""
import os as _os  # release: repository root, override with the PROTCOMPASS_ROOT environment variable
PROTCOMPASS_ROOT = _os.environ.get("PROTCOMPASS_ROOT") or _os.path.abspath(
    _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "../.."))
import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path((PROTCOMPASS_ROOT + "/protcompass"))
BY = ROOT / "probing_results" / "by_source"
sys.path.insert(0, str(ROOT / "scripts"))
from make_panels_original_style import DISP  # noqa: E402

METRIC = ["accuracy", "spearman", "circ_cos", "r2"]
FLOORS = ["ref_length", "ref_position", "ref_aa", "ref_seq_window", "ref_seq_expert", "ref_seq_global", "ref_coords",
          "ref_backbone", "ref_global", "ref_pairhist"]
SEQ_FLOORS = {"ref_length", "ref_position", "ref_aa", "ref_seq_window", "ref_seq_expert", "ref_seq_global"}


def scores():
    """One score per (source, probe): the best readout, as the released comparison uses."""
    rows = []
    for f in sorted(BY.glob("*.csv")):
        d = pd.read_csv(f)
        d["score"] = d[[c for c in METRIC if c in d]].bfill(axis=1).iloc[:, 0]
        d = d.dropna(subset=["score"])
        g = d.groupby(["source", "probe", "dim"], as_index=False).score.mean()
        rows.append(g)
    d = pd.concat(rows, ignore_index=True)
    return d.loc[d.groupby(["source", "probe"]).score.idxmax()].reset_index(drop=True)


def audit():
    a = pd.read_csv(ROOT / "probing_results" / "floor_assignment.csv").rename(columns={"Unnamed: 0": "source"})
    return a.set_index("source").uses_coordinates.astype(bool)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--markdown", action="store_true")
    a = ap.parse_args()
    d = scores()
    uses = audit()
    probes = list(pd.read_csv(ROOT / "probing_results" / "floor_vs_encoders.csv").probe)
    d = d[d.probe.isin(probes)]
    d["is_floor"] = d.source.isin(FLOORS)
    d["logdim"] = np.log(d.dim.clip(lower=1))

    rows = []
    for probe, g in d.groupby("probe"):
        fl = g[g.is_floor]
        en = g[~g.is_floor & g.source.isin(uses.index[uses])]      # coordinate encoders, the side that loses
        if fl.empty or en.empty:
            continue
        # regress the score on log width over every source on this probe, then compare the residuals
        X = np.column_stack([np.ones(len(g)), g.logdim])
        beta = np.linalg.lstsq(X, g.score.to_numpy(), rcond=None)[0]
        res = g.score.to_numpy() - X @ beta
        g = g.assign(resid=res)
        fl_r, en_r = g[g.is_floor], g[~g.is_floor & g.source.isin(uses.index[uses])]
        # width-matched pairs: floors and encoders within a factor of two of one another
        pairs = [(f.source, e.source, f.score - e.score)
                 for f in fl.itertuples() for e in en.itertuples()
                 if 0.5 <= f.dim / max(e.dim, 1) <= 2.0]
        rows.append(dict(probe=probe, slope=beta[1],
                         floor_best=fl.score.max(), enc_best=en.score.max(),
                         gap=fl.score.max() - en.score.max(),
                         gap_resid=fl_r.resid.max() - en_r.resid.max(),
                         n_pairs=len(pairs),
                         pairs_floor_ahead=int(sum(p[2] > 0 for p in pairs)),
                         median_pair_gap=float(np.median([p[2] for p in pairs])) if pairs else np.nan))
    t = pd.DataFrame(rows)
    t.to_csv(ROOT / "probing_results" / "capacity_control.csv", index=False)

    same = int((np.sign(t.gap) == np.sign(t.gap_resid)).sum())
    ahead = int((t.pairs_floor_ahead / t.n_pairs.clip(lower=1) > 0.5).sum())
    if a.markdown:
        print("<!-- generated by scripts/capacity_control.py; do not edit by hand -->\n")
        print("| probe | slope of score on log width | floor - best coordinate encoder | after removing width | "
              "width-matched pairs where the floor leads |")
        print("|---|---|---|---|---|")
        for r in t.itertuples():
            print(f"| {r.probe} | {r.slope:+.3f} | {r.gap:+.3f} | {r.gap_resid:+.3f} | "
                  f"{r.pairs_floor_ahead} of {r.n_pairs} |")
        print(f"\nThe sign of the gap is unchanged by removing width on {same} of {len(t)} probes, and the floor "
              f"leads the majority of width-matched pairs on {ahead} of {len(t)}.")
        return
    print(t.round(3).to_string(index=False))
    print(f"\nsign of the gap unchanged after removing width on {same} of {len(t)} probes")
    print(f"floor leads the majority of width-matched pairs on {ahead} of {len(t)} probes")
    print(f"median slope of score on log width: {t.slope.median():+.3f}")


if __name__ == "__main__":
    main()
