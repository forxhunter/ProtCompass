"""Section 1's comparison under the conditional-floor rule that section 2 establishes.

The headline table holds every encoder to the best of all eight descriptors, which for a sequence-only model means a
descriptor built from coordinates it never received. Section 2 states the rule that should apply instead: an encoder is
held to the floors built from the inputs the audit measured it to use. Under that rule the two groups separate
completely and in opposite directions, which the headline table hides.

This omission was found by the round-6 review. It does not weaken the claim about coordinate encoders; it identifies
who the claim is about, and it surfaces a positive result about sequence models that was in the data all along.

  python emit_conditional_floor_table.py [--latex OUT.tex]
With --latex, also writes the table body for the manuscript (six sequence floors, all ten floors on the coordinate
side, scores read on test) and prints the largest single-cell sequence-side margin.
"""
import os as _os  # release: repository root, override with the PROTCOMPASS_ROOT environment variable
PROTCOMPASS_ROOT = _os.environ.get("PROTCOMPASS_ROOT") or _os.path.abspath(
    _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "../.."))
import sys
import glob
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path((PROTCOMPASS_ROOT + "/protcompass"))
RES = ROOT / "probing_results"
SEQ_FLOORS = ["ref_length", "ref_position", "ref_aa", "ref_seq_window", "ref_seq_expert", "ref_seq_global"]
ALL_FLOORS = SEQ_FLOORS + ["ref_coords", "ref_backbone", "ref_global", "ref_pairhist"]
DETERMINED = ["phi_circular", "psi_circular", "local_curvature", "dssp_3", "dssp_8", "core_surface",
              "contact_density", "distance_bins", "contact_order_len_resid", "radius_of_gyration_len_resid",
              "asphericity_len_resid"]
# Two of the eleven are probes whose own floor contains the label by construction: the kNN distances of
# `ref_coords` determine the contact-density bin on 100.0000% of residues, and `ref_pairhist` holds the
# separation-by-distance profile contact order is computed from. They are reported inside the count and again
# outside it, because a reader should not have to take the tautology on trust.
TAUTOLOGICAL = ["contact_density", "contact_order_len_resid"]
LABEL = {"phi_circular": "phi", "psi_circular": "psi", "local_curvature": "local curvature", "dssp_3": "DSSP-3",
         "dssp_8": "DSSP-8", "core_surface": "core / surface", "contact_density": "contact density",
         "distance_bins": "CA distance bins", "contact_order_len_resid": "contact order",
         "radius_of_gyration_len_resid": "radius of gyration", "asphericity_len_resid": "asphericity"}


def main():
    d = pd.concat([pd.read_csv(f) for f in glob.glob(str(RES / "by_source" / "*.csv"))], ignore_index=True)
    d["headline"] = d["pearson"].fillna(d["circ_cos"] if "circ_cos" in d else np.nan).fillna(d["balanced_accuracy"])
    d["family"] = np.where(d.readout == "linear", "linear", "nonlinear")
    m = d.groupby(["source", "probe", "family"]).headline.mean().reset_index()
    best = m.loc[m.groupby(["source", "probe"]).headline.idxmax()]
    wide = best.pivot(index="source", columns="probe", values="headline")
    audit = pd.read_csv(RES / "floor_assignment.csv").rename(columns={"Unnamed: 0": "source"}).set_index("source")

    enc = [i for i in wide.index if not i.startswith("ref_")]
    seq = [e for e in enc if e in audit.index and not audit.loc[e, "uses_coordinates"]]
    crd = [e for e in enc if e in audit.index and audit.loc[e, "uses_coordinates"]]

    rows = []
    for p in (x for x in DETERMINED if x in wide.columns):
        sf = wide.loc[[f for f in SEQ_FLOORS if f in wide.index], p].max()
        af = wide.loc[[f for f in ALL_FLOORS if f in wide.index], p].max()
        s = wide.loc[seq, p].dropna()
        c = wide.loc[crd, p].dropna()
        rows.append(dict(probe=p, seq_floor=sf, all_floor=af, n_seq=len(s), seq_below=int((s < sf).sum()),
                         seq_min_margin=(s - sf).min(), n_crd=len(c), crd_below=int((c < af).sum())))
    t = pd.DataFrame(rows)

    print("<!-- generated by scripts/emit_conditional_floor_table.py -->\n")
    print(f"| determined probe | sequence floor | sequence-only encoders below it | smallest margin | "
          f"coordinate floor | coordinate encoders below it |")
    print("|---|---|---|---|---|---|")
    for r in t.itertuples():
        print(f"| {LABEL.get(r.probe, r.probe)} | {r.seq_floor:.4f} | {r.seq_below} of {r.n_seq} | "
              f"{r.seq_min_margin:+.3f} | {r.all_floor:.4f} | {r.crd_below} of {r.n_crd} |")
    cell_max = max((wide.loc[seq, r.probe].dropna() - r.seq_floor).max() for r in t.itertuples())
    print(f"largest single-cell sequence-side margin: {cell_max:+.3f}")
    if "--latex" in sys.argv:
        out = Path(sys.argv[sys.argv.index("--latex") + 1])
        tex = {"phi_circular": "$\\phi$", "psi_circular": "$\\psi$", "local_curvature": "Local curvature",
               "dssp_3": "DSSP-3", "dssp_8": "DSSP-8", "core_surface": "Core / surface",
               "contact_density": "Contact density", "distance_bins": "CA distance bins",
               "contact_order_len_resid": "Contact order", "radius_of_gyration_len_resid": "Radius of gyration",
               "asphericity_len_resid": "Asphericity"}
        L = ["% generated by scripts/emit_conditional_floor_table.py --latex; do not edit by hand",
             "\\begin{tabular}{lrlrrl}", "\\toprule",
             "\\textbf{Determined probe} & \\textbf{Seq.\\ floor} & \\textbf{Seq.\\ enc.\\ below} & "
             "\\textbf{Smallest margin} & \\textbf{Coord.\\ floor} & \\textbf{Coord.\\ enc.\\ below} \\\\",
             "\\midrule"]
        for r in t.itertuples():
            L.append(f"{tex[r.probe]} & {r.seq_floor:.4f} & {r.seq_below} of {r.n_seq} & {r.seq_min_margin:+.3f} & "
                     f"{r.all_floor:.4f} & {r.crd_below} of {r.n_crd} \\\\")
        L += ["\\bottomrule", "\\end{tabular}"]
        out.write_text("\n".join(L) + "\n")
        print("wrote", out)
    inf = t[~t.probe.isin(TAUTOLOGICAL)] if "probe" in t else t
    print(f"\n**{t.seq_below.sum()} of {t.n_seq.sum()}** sequence-only encoder cells fall below the floor built from "
          f"the inputs those models receive, at margins from {t.seq_min_margin.min():+.3f} upward. "
          f"**{t.crd_below.sum()} of {t.n_crd.sum()}** coordinate-encoder cells fall below the floor built from "
          f"theirs. Dropping the two probes whose floor contains the label by construction leaves "
          f"**{inf.seq_below.sum()} of {inf.n_seq.sum()}** and **{inf.crd_below.sum()} of {inf.n_crd.sum()}**.\n")


if __name__ == "__main__":
    main()
