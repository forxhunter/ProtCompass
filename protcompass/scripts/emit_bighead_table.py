"""The four multi-output held-out tasks, against both nulls.

Reads confirmation_downstream/bighead_matched/remote_holdout.csv, which scores the intact arm, the erased arm, four
permuted shams and four variance-matched nulls for every cell, and writes the table the appendix inputs.

  python emit_bighead_table.py > .../generated/bighead_holdout.tex
"""
import os as _os  # release: repository root, override with the PROTCOMPASS_ROOT environment variable
PROTCOMPASS_ROOT = _os.environ.get("PROTCOMPASS_ROOT") or _os.path.abspath(
    _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "../.."))
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import binomtest

ROOT = Path((PROTCOMPASS_ROOT + "/protcompass"))
SRC = ROOT / "confirmation_downstream" / "bighead_matched" / "remote_holdout.csv"
LABEL = {"ec_classification": "EC classification", "go_bp": "GO-BP", "go_mf": "GO-MF",
         "remote_homology": "remote homology"}


def cells(d):
    for (task, enc), g in d.groupby(["task", "encoder"]):
        p = g.pivot_table(index="arm", columns="descriptor", values="score")
        fam = {k: [a for a in p.index if a.startswith(k)] for k in ("sham", "null")}
        if not fam["sham"] or not fam["null"] or "erased" not in p.index:
            continue
        rec = dict(task=task, encoder=enc, intact=p.loc["intact", "none"])
        for k, arms in fam.items():
            lvl = p.loc[arms, "none"].mean()
            rec[f"effect_{k}"] = lvl - p.loc["erased", "none"]
            rec[f"above_{k}"] = bool(lvl > rec["intact"])
            for q in ("named", "permuted", "other"):
                if q in p.columns and not p.loc[arms, q].isna().all():
                    rec[f"R_{q}_{k}"] = ((p.loc["erased", q] - p.loc["erased", "none"])
                                         - (p.loc[arms, q] - p.loc[arms, "none"]).mean())
        yield rec


def main():
    C = pd.DataFrame(list(cells(pd.read_csv(SRC))))
    print("% generated by scripts/emit_bighead_table.py; do not edit by hand")
    print("\\begin{tabular}{lrrrrrrrr}")
    print("\\toprule")
    print(" & \\multicolumn{3}{c}{against the permuted sham} & \\multicolumn{3}{c}{against the matched null} & "
          "\\multicolumn{2}{c}{above intact} \\\\")
    print("\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}\\cmidrule(lr){8-9}")
    print("task & effect & positive & sign $p$ & effect & positive & $R$ named & sham & null \\\\")
    print("\\midrule")
    for task in ("ec_classification", "go_bp", "go_mf", "remote_homology"):
        g = C[C.task == task]
        if not len(g):
            continue
        n = len(g)
        k = int((g.effect_sham > 0).sum())
        pv = binomtest(k, n, 0.5, alternative="greater").pvalue
        print(f"{LABEL[task]} & ${g.effect_sham.mean():+.4f}$ & {k} / {n} & ${pv:.2f}$ & "
              f"${g.effect_null.mean():+.4f}$ & {int((g.effect_null > 0).sum())} / {n} & "
              f"${g.R_named_null.mean():+.4f}$ & {int(g.above_sham.sum())} / {n} & "
              f"{int(g.above_null.sum())} / {n} \\\\")
    print("\\bottomrule")
    print("\\end{tabular}")
    print("% six encoders per task, four permuted shams and four variance-matched nulls; heads fitted on the "
          "released stage-1 training split")


if __name__ == "__main__":
    main()
