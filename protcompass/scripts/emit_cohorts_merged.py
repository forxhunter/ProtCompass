"""One table for the two CATH 4.4 probing cohorts (appendix, confirmation).

Merges the tables written by confirmation_report.py --latex (cohort A) and confirmation2_report.py --latex (cohort B):
the frozen predictions are shared, and each cohort gets its own result and verdict columns. Nothing is recomputed; the
script checks that the predictions H1 to H4 are worded identically in the two tables.

  python emit_cohorts_merged.py cohort_a.tex cohort_b.tex > confirmation_cohorts.tex
"""
import re
import sys
from pathlib import Path


def rows(path):
    out = {}
    for line in Path(path).read_text().split("\n"):
        m = re.match(r"^(H\w+) & (.*) \\\\\s*$", line)
        if m:
            cells = m.group(2).split(" & ")
            assert len(cells) == 3, line
            out[m.group(1)] = cells
    return out


def main():
    A, B = rows(sys.argv[1]), rows(sys.argv[2])
    assert list(A) == ["H1", "H2", "H3", "H4"] and list(B)[:4] == ["H1", "H2", "H3", "H4"]
    for h in A:
        assert A[h][0] == B[h][0], f"{h}: the two cohorts word the prediction differently"
    print("% generated by scripts/emit_cohorts_merged.py from the tables of confirmation_report.py and")
    print("% confirmation2_report.py; do not edit by hand")
    print(r"\begin{adjustbox}{max width=\linewidth}")
    print(r"\begin{tabular}{lp{0.30\linewidth}p{0.22\linewidth}lp{0.22\linewidth}l}")
    print(r"\toprule")
    print(r"\rowcolor{CompassLavender!32}")
    print(r"& prediction, fixed before the cohort was scored & result on cohort A & verdict & result on cohort B & verdict \\")
    print(r"\midrule")
    for h, (claim, res_b, ver_b) in B.items():
        res_a, ver_a = (A[h][1], A[h][2]) if h in A else ("--", "")
        print(f"{h} & {claim} & {res_a} & {ver_a} & {res_b} & {ver_b} \\\\")
    print(r"\bottomrule")
    print(r"\end{tabular}")
    print(r"\end{adjustbox}")


if __name__ == "__main__":
    main()
