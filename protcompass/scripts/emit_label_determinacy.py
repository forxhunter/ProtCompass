"""The numerical determinacy check as a LaTeX table: every determined label, its derivation, and the largest error.

Reads probing_results/label_determinacy.csv, written by scripts/check_label_determinacy.py, and writes the tabular of
Appendix sec:appendix_determinacy (generated/label_determinacy.tex). Only the eleven labels the stored atoms determine
are listed; the reasons for the three undetermined labels and for fold architecture are in Table tab:determinacy.
Nothing is recomputed here. The one extra quantity is the coverage of the CA-distance check: check_label_determinacy.py
compares the stored pair distances of the first 50 of its 400 sampled domains, read from the first 1,000,000 rows of
the pair table, so this script counts those domains and pairs with the same seed and the same cut, reading only the
index arrays of probing_data/labels.h5.

  python emit_label_determinacy.py
"""
import os as _os  # release: repository root, override with the PROTCOMPASS_ROOT environment variable
PROTCOMPASS_ROOT = _os.environ.get("PROTCOMPASS_ROOT") or _os.path.abspath(
    _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "../.."))
from pathlib import Path

import h5py
import numpy as np
import pandas as pd

ROOT = Path((PROTCOMPASS_ROOT + "/protcompass"))
OUT = Path((PROTCOMPASS_ROOT + "/protcompass/paper/generated/label_determinacy.tex"))
N_DOMAINS, SEED, N_PAIR_DOMAINS, PAIR_ROWS = 400, 0, 50, 1_000_000       # as in check_label_determinacy.py

NAME = {"phi": "backbone $\\phi$", "psi": "backbone $\\psi$", "core / surface": "core/surface"}
UNIT = {"rad": "rad", "A": "\\AA", "count": "(count)", "label": "(class label)", "unitless": "(unitless)"}


def tex(s):
    """The plain-text derivations of the CSV in LaTeX: angstrom, en dashes, residue indices in math."""
    s = s.replace("sqrt of", "square root of").replace("CA-CA", "CA--CA")
    s = s.replace(" A,", "~\\AA,").replace(" A ", "~\\AA{} ")
    if s.endswith(" A"):
        s = s[:-2] + "~\\AA"
    for i in ("i-1", "i+1", "i"):
        s = s.replace(f"({i})", f"(${i.replace('-', '{-}').replace('+', '{+}')}$)")
    return s


def error(v, unit):
    if v == 0:
        return f"0 {UNIT[unit]}"
    m, e = f"{v:.1e}".split("e")
    return f"${m}\\times 10^{{{int(e)}}}$ {UNIT[unit]}"


def pair_coverage():
    """Domains and pairs behind the CA-distance row, selected exactly as check_label_determinacy.py selects them."""
    with h5py.File(ROOT / "probing_data" / "labels.h5", "r") as h:
        n = len(h["protein/length"])
        sel = np.random.default_rng(SEED).choice(n, N_DOMAINS, replace=False)
        qp = h["pair/protein_index"][:PAIR_ROWS]
    keep = np.isin(qp, sel[:N_PAIR_DOMAINS])
    return int(len(np.unique(qp[keep]))), int(keep.sum())


def main():
    d = pd.read_csv(ROOT / "probing_results" / "label_determinacy.csv")
    d = d[d["determined by the input"] == "yes"]
    n_dom, n_pairs = pair_coverage()
    L = ["% generated by scripts/emit_label_determinacy.py; do not edit by hand",
         "% source: protcompass/probing_results/label_determinacy.csv (scripts/check_label_determinacy.py)",
         f"% CA distance bins: {n_pairs} stored pairs of {n_dom} domains (the first {N_PAIR_DOMAINS} of the "
         f"{N_DOMAINS} sampled, within the first {PAIR_ROWS} rows of the pair table)",
         "\\begin{tabular}{lp{0.40\\linewidth}rl}",
         "\\toprule",
         "label & derivation from the stored atoms & domains & largest error \\\\",
         "\\midrule"]
    for r in d.itertuples(index=False):
        label, deriv, err, unit = r[0], r[2], r[3], r[4]
        if pd.isna(err):
            # contact order and DSSP are established by derivation; the CSV keeps the reason in its unit column
            deriv, dom, cell = f"{deriv}; {unit}", "--", "not recomputed"
        else:
            dom = f"{n_dom} ({n_pairs:,} pairs)".replace(",", "{,}") if label == "CA distance bins" else str(N_DOMAINS)
            cell = error(float(err), unit)
        L.append(f"{NAME.get(label, label)} & {tex(deriv)} & {dom} & {cell} \\\\")
    L += ["\\bottomrule", "\\end{tabular}"]
    OUT.write_text("\n".join(L) + "\n")
    print("\n".join(L))
    print(f"\nwritten: {OUT}")


if __name__ == "__main__":
    main()
