"""The downstream tasks read against a non-learned reference, the way the probes are read against their floors.

`ref_composition` is amino-acid composition, log length and length/600, scored through the identical downstream
protocol (`scripts/make_downstream_reference.py`, `extract/score2.py`). It answers the question the probing side
already answers and the downstream side did not: how much of each task's score survives with no learned
representation at all.

  python downstream_reference_table.py [--markdown]
"""
import os as _os  # release: repository root, override with the PROTCOMPASS_ROOT environment variable
PROTCOMPASS_ROOT = _os.environ.get("PROTCOMPASS_ROOT") or _os.path.abspath(
    _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "../.."))
import argparse
from pathlib import Path

import pandas as pd

ROOT = Path((PROTCOMPASS_ROOT + "/protcompass"))
REF = "ref_composition"
LABEL = {"ec_classification": "EC", "go_mf": "GO-MF", "go_bp": "GO-BP",
         "subcellular_localization": "localisation", "remote_homology": "homology", "solubility": "solubility",
         "stability": "stability", "fluorescence": "fluorescence", "ppi_affinity": "affinity",
         "membrane_soluble": "membrane"}
METRIC = {"ec_classification": "accuracy", "go_mf": "F-max", "go_bp": "F-max",
          "subcellular_localization": "accuracy", "remote_homology": "accuracy", "solubility": "AUROC",
          "stability": "Spearman", "fluorescence": "Spearman", "ppi_affinity": "Spearman",
          "membrane_soluble": "AUROC"}
ORDER = ["ec_classification", "go_mf", "go_bp", "subcellular_localization", "remote_homology", "solubility",
         "membrane_soluble", "stability", "fluorescence", "ppi_affinity"]


def table():
    d = pd.read_csv(ROOT / "extract" / "scores2_selected.csv")
    w = d.pivot(index="encoder", columns="task", values="score")
    sd = d.pivot(index="encoder", columns="task", values="seed_sd")
    ref, enc = w.loc[REF], w.drop(index=REF)
    rows = []
    for t in [t for t in ORDER if t in w.columns]:
        col = enc[t].dropna()
        rows.append(dict(task=LABEL[t], metric=METRIC[t], reference=ref[t], reference_sd=sd.loc[REF, t],
                         median_encoder=col.median(), best_encoder=col.max(), best=col.idxmax(),
                         above=int((col > ref[t]).sum()), n=len(col),
                         margin_median=col.median() - ref[t], margin_best=col.max() - ref[t]))
    return pd.DataFrame(rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--markdown", action="store_true")
    a = ap.parse_args()
    t = table()
    if not a.markdown:
        print(t.round(3).to_string(index=False))
        print(f"\ntasks where the median encoder is within 0.02 of the reference: "
              f"{', '.join(t.task[t.margin_median < 0.02])}")
        return
    print("<!-- generated by scripts/downstream_reference_table.py; do not edit by hand -->\n")
    print("| task | metric | composition reference | median encoder | best encoder | encoders above the reference |")
    print("|---|---|---|---|---|---|")
    for r in t.itertuples():
        print(f"| {r.task} | {r.metric} | {r.reference:.3f} | {r.median_encoder:.3f} | {r.best_encoder:.3f} "
              f"({r.best}) | {r.above} of {r.n} |")
    near = list(t.task[t.margin_median < 0.02])
    print(f"\nThe reference is amino-acid composition, log length and length/600 through the identical protocol. "
          f"The median encoder clears it on every task, but by less than 0.02 on "
          f"{len(near)} of {len(t)}: {', '.join(near)}.")


if __name__ == "__main__":
    main()
