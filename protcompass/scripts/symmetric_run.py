NBR_SETS = ["CA", "N+CA+C", "N+CA+C+O", "N+CA+CB", "N+CA+C+O+CB"]
NBR_K = (4, 8, 16)
KMAX = 16
NBR_SOURCES = [f"ref_nbr{k}@{s}" for k in NBR_K for s in NBR_SETS]

RESIDUE = [  # name, label dataset(s), kind, n_out
    ("phi_circular", ("phi_sin", "phi_cos"), "circ", 2), ("psi_circular", ("psi_sin", "psi_cos"), "circ", 2),
    ("local_curvature", "curvature", "reg", 1),
    ("dssp_3", "dssp3", "clf", 3), ("dssp_8", "dssp8", "clf", 8),
    ("rsa", "rsa", "reg", 1), ("rsa_bins", "rsa_bin", "clf", 3), ("bfactor", "bfactor_z", "reg", 1),
    ("core_surface", "core", "clf", 2), ("contact_density", "contact_density_bin", "clf", 4),
    ("dssp3_control", None, "clf", 3),
]
PROTEIN = [("contact_order_len_resid", "reg", 1), ("radius_of_gyration_len_resid", "reg", 1),
           ("asphericity_len_resid", "reg", 1), ("architecture_label", "clf", None)]


# ----------------------------------------------------------------------------- the neighbourhood floor family
def _nbr_one(args):
    L, stored = args
    out = {}
    for s in NBR_SETS:
        names = s.split("+")
        ai = [pf.STORED.index(a) for a in names]
        xyz = stored[:, ai].reshape(-1, 3).astype(np.float64)
        res_of = np.repeat(np.arange(L), len(ai))
        elem = np.array([pf.element(a) for a in names] * L)
        out[s] = pf.neighbourhood(xyz, res_of, elem, L, sorted({pf.element(a) for a in names}))
    return out


def nbr_slice(X, atoms, k):
    """Columns of the K = 16 descriptor that make up the K = k descriptor: per query class the presence flag, and per
    (query, target) pair the k smallest distances, their k separations and the five shell counts."""
    C = len({pf.element(a) for a in atoms.split("+")})
    cols, c = [], 0
    for _ in range(C):
        cols.append(c); c += 1
        for _ in range(C):
            cols += list(range(c, c + k)); c += KMAX
            cols += list(range(c, c + k)); c += KMAX
            cols += list(range(c, c + len(pf.SHELLS))); c += len(pf.SHELLS)
    assert c == X.shape[1], (atoms, c, X.shape)
    return X[:, cols]


def build_nbr(data, workers):
    pf.K = KMAX
    coords = data.R["coords"]
    NBR_CACHE.mkdir(parents=True, exist_ok=True)
    for p in rps.PARTS:
        if all((NBR_CACHE / f"{s}__{p}.npy").exists() for s in NBR_SETS):
            continue
        jobs = [(int(data.L[i]), coords[data.offs[i]:data.offs[i] + data.L[i]]) for i in data.chosen[p]]
        with Pool(workers) as pool:
            res = pool.map(_nbr_one, jobs, chunksize=4)
        for s in NBR_SETS:
            a = np.concatenate([r[s] for r in res])
            assert len(a) == len(data.rows[p]) and np.isfinite(a).all(), (s, p, a.shape)
            np.save(NBR_CACHE / f"{s}__{p}.npy", a.astype(np.float32))
            print(f"nbr {s:14s} {p:5s} {a.shape}", flush=True)
    # K = 8 on the four stored-atom sets is the frozen pre-registered floor; the slice must reproduce it
    if SPLIT == "superfamily":
        for s in NBR_SETS[:4]:
            frozen = np.load(pf.cache_dir() / f"ref_atom_neighborhood@{s}__train.npy", mmap_mode="r")[:5000]
            mine = nbr_slice(np.load(NBR_CACHE / f"{s}__train.npy", mmap_mode="r")[:5000], s, 8)
            assert np.allclose(frozen, mine, atol=1e-4), s
        print("K = 8 slice equals the frozen pre-registered floor on the four stored-atom sets", flush=True)


# ----------------------------------------------------------------------------- data
class SymData(pf.PreregData):
    def residue_features(self, source):
        if source.startswith("ref_nbr"):
            k, s = source[len("ref_nbr"):].split("@")
            return {p: nbr_slice(np.load(NBR_CACHE / f"{s}__{p}.npy"), s, int(k)) for p in rps.PARTS}
        if source.endswith("_vframe"):
            emb = np.load(VFRAME / source / "residue_fp16.npy", mmap_mode="r")
            return {p: np.asarray(emb[self.rows[p]], dtype=np.float32) for p in rps.PARTS}
        return super().residue_features(source)

    def protein_features(self, source):
        if source.endswith("_vframe"):
            X = np.load(VFRAME / source / "pooled_fp32.npy")
            return {p: X[self.prot_idx[p]].astype(np.float32) for p in rps.PARTS}
        return super().protein_features(source)

    def control_labels(self):
        """Hewitt-Liang control task for DSSP-3: a fixed random map from residue type to a DSSP-3 class."""
        tr = self.R["dssp3"][:][self.rows["train"]]
        freq = np.bincount(tr[tr >= 0], minlength=3) / (tr >= 0).sum()
        amap = np.random.default_rng(0).choice(3, size=20, p=freq)
        return {p: np.where(self.aa[self.rows[p]] < 20, amap[np.clip(self.aa[self.rows[p]], 0, 19)], -1).astype(np.int64)
                for p in rps.PARTS}


def headline(kind, sc):
    return sc["pearson"] if kind == "reg" else sc["circ_cos"] if kind == "circ" else sc["balanced_accuracy"]


# ----------------------------------------------------------------------------- fitting
def fit_both(X, y, kind, n_out, pairs=None):
    """Every readout fitted once; its validation and test score, and its test prediction."""
    nv = len(y["val"])
    Xc = {"train": X["train"], "val": X["val"], "test": torch.cat([X["val"], X["test"]])}
    yc = {"train": y["train"], "val": y["val"], "test": np.concatenate([y["val"], y["test"]])}
    pc = None
    if pairs is not None:
        off = X["val"].shape[0]
        pc = {"train": pairs["train"], "val": pairs["val"],
              "test": tuple(torch.cat([pairs["val"][t], pairs["test"][t] + off]) for t in (0, 1))}
    runs = []
    if pairs is None:
        if kind == "clf":
            runs.append(("linear", 0, rps.fit(Xc, yc, kind, n_out, 0, 0)))
        else:
            runs.append(("linear", 0, rps.ridge(X["train"], y["train"], X["val"], y["val"], Xc["test"])))
    for s in rps.MLP_SEEDS:
        runs.append(("pair_mlp" if pairs is not None else "mlp2", s, rps.fit(Xc, yc, kind, n_out, rps.HIDDEN, s, pc)))
    rows, preds = [], {}
    for readout, seed, p in runs:
        for split, part, yy in (("val", p[:nv], y["val"]), ("test", p[nv:], y["test"])):
            sc = rps.score(kind, yy, part, y["train"])
            rows.append(dict(readout=readout, seed=seed, split=split, n=len(yy), headline=headline(kind, sc), **sc))
        preds[f"{readout}_{seed}"] = p[nv:]
    return rows, preds


def run_source(data, source):
    t0, rows, saved = time.time(), [], {}

    def add(probe, level, res, y, prot, preds):
        for r in res:
            rows.append(dict(source=source, probe=probe, level=level, **r))
        saved[probe] = dict(y=y, protein=prot, **preds)
        print(f"  [{time.time() - t0:5.0f}s] {source}: {probe}", flush=True)

    pooled_only = source == "foldvision"
    if not pooled_only:
        raw = data.residue_features(source)
        X = dict(zip(rps.PARTS, rps.standardise(raw["train"], raw["val"], raw["test"]))); del raw
        control = data.control_labels()
        for name, ds, kind, n_out in RESIDUE:
            if ds is None:
                lab = control
            else:
                lab = {p: (np.stack([data.R[d][:][data.rows[p]] for d in ds], 1) if isinstance(ds, tuple)
                           else data.R[ds][:][data.rows[p]]) for p in rps.PARTS}
            ok = {p: (~np.isnan(lab[p]).reshape(len(lab[p]), -1).any(1) if kind != "clf" else lab[p] >= 0) for p in rps.PARTS}
            Xp = {p: X[p][torch.from_numpy(np.where(ok[p])[0]).to(rps.DEV)] for p in rps.PARTS}
            y = {p: (lab[p][ok[p]].astype(np.int64) if kind == "clf" else lab[p][ok[p]].astype(np.float64)) for p in rps.PARTS}
            res, preds = fit_both(Xp, y, kind, n_out)
            add(name, "residue", res, y["test"], data.pidx[data.rows["test"]][ok["test"]], preds); del Xp
        res, preds = fit_both(X, data.pair_y, "clf", 16, pairs=data.pairs)
        add("distance_bins", "pair", res, data.pair_y["test"], data.pair_prot["test"], preds)
        del X; torch.cuda.empty_cache()
    if not source.startswith("ref_nbr"):
        praw = data.protein_features(source)
        PX = dict(zip(rps.PARTS, rps.standardise(praw["train"], praw["val"], praw["test"])))
        for name, kind, n_out in PROTEIN:
            y_all = data.P[f"{name[:-len('_len_resid')]}_len_resid_{SPLIT}" if name.endswith("_len_resid")
                           else f"{name}_{SPLIT}"][:]
            y_all = y_all.astype(np.int64 if kind == "clf" else np.float64)
            ok = {p: (y_all[data.prot_idx[p]] >= 0) if kind == "clf" else np.isfinite(y_all[data.prot_idx[p]])
                  for p in rps.PARTS}
            PXo = {p: PX[p][torch.from_numpy(np.where(ok[p])[0]).to(rps.DEV)] for p in rps.PARTS}
            y = {p: y_all[data.prot_idx[p]][ok[p]] for p in rps.PARTS}
            res, preds = fit_both(PXo, y, kind, int(y_all.max()) + 1 if kind == "clf" else n_out)
            add(name, "protein", res, y["test"], data.prot_idx["test"][ok["test"]], preds)
        del PX; torch.cuda.empty_cache()
    sub = OUT / "by_source"
    sub.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(rows).to_csv(sub / f"{source}.csv", index=False)
    np.savez_compressed(sub / f"{source}__test_predictions.npz",
                        **{f"{k}|{kk}": v for k, d in saved.items() for kk, v in d.items()})
    print(f"[{source}] {len(rows)} rows, {time.time() - t0:.0f}s", flush=True)


def check_freeze():
    if SPLIT == "superfamily":
        return
    f = SYM / f"freeze_{SPLIT}.json"
    if not f.exists():
        raise SystemExit(f"{f} does not exist: freeze before scoring the {SPLIT} split")
    rec = json.loads((SYM / f"freeze_{SPLIT}.sha256.json").read_text())
    if hashlib.sha256(f.read_bytes()).hexdigest() != rec["sha256"]:
        raise SystemExit(f"{f} changed after it was frozen")


def main():
    data = SymData()
    qp = data.Q["protein_index"][:]
    data.pair_prot = {p: qp[np.isin(qp, data.chosen[p])] for p in rps.PARTS}
    if "--build-nbr" in sys.argv:
        w = int(sys.argv[sys.argv.index("--workers") + 1]) if "--workers" in sys.argv else 8
        return build_nbr(data, w)
    check_freeze()
    sources = [a for a in sys.argv[1:] if not a.startswith("--")]
    todo = [s for s in sources if not (OUT / "by_source" / f"{s}.csv").exists()]
    print(f"split {SPLIT}; device {rps.DEV}; to score: {todo}", flush=True)
    for s in todo:
        lock = OUT / "by_source" / f"{s}.lock"
        if (OUT / "by_source" / f"{s}.csv").exists():
            continue
        try:                            # several processes share one source list; the first to claim a source runs it
            (OUT / "by_source").mkdir(parents=True, exist_ok=True)
            lock.touch(exist_ok=False)
        except FileExistsError:
            continue
        for attempt in range(12):
            try:
                run_source(data, s)
                break
            except (torch.OutOfMemoryError, RuntimeError) as e:
                if "out of memory" not in str(e).lower():
                    raise
                torch.cuda.empty_cache()
                print(f"[{s}] CUDA out of memory (attempt {attempt + 1}/12); waiting 3 min", flush=True)
                time.sleep(180)


if __name__ == "__main__":
    main()
