"""Rerun of the released probing comparison with one protocol for encoders and floors.

The released sweep scored every source (encoder or floor) on the test split only, and the better readout family of an
encoder was taken on test. This run fits every readout once on the training part (ridge penalty and MLP early stopping
on validation, exactly as released), predicts the validation and the test part from that one fit, and saves the test
predictions with the protein each row belongs to. The readout family of every source, encoder or floor, can then be
chosen on validation, and every encoder-minus-floor gap gets a protein-level paired bootstrap interval
(scripts/symmetric_decide.py). Nothing here selects anything.

Probes: the fifteen of the floor comparison, and one control task in the sense of Hewitt and Liang (2019) for DSSP-3,
in which each amino-acid type is mapped to a DSSP-3 class drawn once (seed 0) from the training class frequencies.

Sources: encoders (probing_embeddings/, and probing_embeddings_vframe/ for the frame-projected equivariant
re-extraction), the released floors, the atom-matched floors (`ref_backbone@S`, `ref_global@S`), and a label-agnostic
floor family generated by one rule, `ref_nbr{K}@S`: for the atom set S an encoder reads, grouped by element, the K
nearest atoms of other residues (distance and signed sequence separation) and the atom counts within 3.5, 5, 7.5, 10 and
13 A, for K in 4, 8 and 16 (scripts/prereg_floors.py `neighbourhood`, with K = 8 the frozen pre-registered floor).
The family is residue-level, so it enters the residue and pair probes only.

  SYM_SPLIT=superfamily python symmetric_run.py SOURCE [SOURCE ...]
  SYM_SPLIT=topology    python symmetric_run.py SOURCE ...   # refuses unless symmetric/freeze_topology.json is frozen
  SYM_SPLIT=... python symmetric_run.py --build-nbr [--workers 8]   # cache the neighbourhood family for the split

Output: symmetric/results_<split>/by_source/<source>.csv (validation and test score of every readout and seed) and
<source>__test_predictions.npz (per probe: y, protein, and the test prediction of every readout and seed).
"""
