"""Composition on stability, the one demand that survives every control, with a nonlinear head and with a nonlinear
erasure, against the linear result on the same encoders.

  mlp      the released pipeline with the released downstream MLP (two hidden layers of width 512) as the head in
           every arm (scripts/addback_named_pairs.py --head mlp; erasure/named_pairs_mlp_stability/)
  kernel   LEACE, the variance-matched null, the sham and the linear head in a random Fourier feature space of a
           Gaussian kernel (scripts/addback_kernel.py; erasure/named_pairs_kernel/)
  linear   the released cells of the full grid (erasure/named_pair_cells_full.csv) on the same encoders

Output: erasure/stability_nonlinear.csv (one row per variant), stability_nonlinear_cells.csv (per encoder)
"""
import os as _os  # release: repository root, override with the PROTCOMPASS_ROOT environment variable
PROTCOMPASS_ROOT = _os.environ.get("PROTCOMPASS_ROOT") or _os.path.abspath(
    _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "../.."))
import sys
from pathlib import Path

import pandas as pd
from scipy.stats import binomtest

ROOT = Path((PROTCOMPASS_ROOT + "/protcompass"))
sys.path.insert(0, str(ROOT / "scripts"))
from named_pair_verdicts import cells, load                              # noqa: E402

E = ROOT / "erasure"
out, per = [], []
L = pd.read_csv(E / "named_pair_cells_full.csv")
L = L[(L.task == "stability") & (L.concept == "amino-acid composition")]
for name, src in (("mlp", E / "named_pairs_mlp_stability"), ("kernel", E / "named_pairs_kernel")):
    if not src.exists() or not any(src.glob("*.csv")):
        continue
    C = cells(load([src]))
    C = C[(C.task == "stability") & (C.concept == "amino-acid composition")]
    lin = L[L.encoder.isin(C.encoder)]
    for variant, g in ((name, C), (f"linear, same encoders as {name}", lin)):
        pos = int((g.R_null > 0).sum())
        out.append(dict(variant=variant, n=len(g), R_var=g.R_null.mean(), pos=pos,
                        p=binomtest(pos, len(g), 0.5).pvalue, effect_var=g.effect_null.mean(),
                        R_perm=g.Rperm_null.mean() if "Rperm_null" in g else float("nan"),
                        passes=bool(binomtest(pos, len(g), 0.5).pvalue < 0.05 and g.R_null.mean() >= 0.02)))
    per.append(C.assign(variant=name))
R = pd.DataFrame(out)
R.to_csv(E / "stability_nonlinear.csv", index=False)
if per:
    pd.concat(per).to_csv(E / "stability_nonlinear_cells.csv", index=False)
print(R.round(4).to_string(index=False))


def latex():
    lab = {"mlp": "two-layer head", "linear, same encoders as mlp": "linear head, same encoders",
           "kernel": "kernel-space erasure", "linear, same encoders as kernel": "linear erasure, same encoders"}
    lines = ["% generated by scripts/stability_nonlinear_summary.py; do not edit by hand",
             "\\begin{tabular}{lrrrrr}", "\\toprule",
             "variant & encoders & $R_{\\mathrm{var}}$ & positive & sign test $p$ & permuted descriptor \\\\", "\\midrule"]
    for r in R.itertuples():
        pstr = "$<0.001$" if r.p < 0.001 else f"${r.p:.3f}$"
        lines.append(f"{lab.get(r.variant, r.variant)} & {r.n} & ${r.R_var:+.3f}$ & {r.pos} & {pstr} & ${r.R_perm:+.4f}$ \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


for d in sys.argv[1:]:
    Path(d, "stability_nonlinear.tex").write_text(latex())
