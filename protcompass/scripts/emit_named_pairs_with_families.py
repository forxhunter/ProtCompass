"""The 60-pair repair-rule table with the family-weighted verdict as two extra columns (appendix, repair rule).

Reads erasure/named_pair_verdicts_full.csv (scripts/named_pair_verdicts.py) and erasure/family_weighted_repair_full.csv
(scripts/family_weighted_repair.py); nothing is recomputed. The first nine columns are written exactly as
named_pair_verdicts.py --latex writes them, which the script checks against the released table when it is given.

  python emit_named_pairs_with_families.py [--check path/to/named_pairs_full.tex]
      writes erasure/named_pairs_full_families.tex
"""
import os as _os  # release: repository root, override with the PROTCOMPASS_ROOT environment variable
PROTCOMPASS_ROOT = _os.environ.get("PROTCOMPASS_ROOT") or _os.path.abspath(
    _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "../.."))
import argparse
import re
from pathlib import Path

import pandas as pd

import named_pair_verdicts as npv

ROOT = Path((PROTCOMPASS_ROOT + "/protcompass"))


def row_base(r):
    star = "$^{\\ast}$" if r.named_by_effect_rule else ""
    verdict = "yes" if r.passes_R_rule else ("sign only" if r.passes_R_sign else "")
    return (f"{npv.LABEL.get(r.task, r.task)}{star} & {npv.SHORT.get(r.concept, r.concept)} & {r.n} & "
            f"${r.eff_null:+.4f}$ & {r.eff_pos_null} & ${r.R_null:+.4f}$ & {r.pos_null} & "
            f"${npv.fmt_p(r.p_null_holm)}$ & {verdict}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", help="the released named_pairs_full.tex; its rows must equal the first nine columns")
    a = ap.parse_args()
    V = pd.read_csv(ROOT / "erasure" / "named_pair_verdicts_full.csv")
    Fm = pd.read_csv(ROOT / "erasure" / "family_weighted_repair_full.csv").set_index(["task", "concept"])
    assert len(V) == 60 and len(Fm) == 60
    base = [row_base(r) for r in V.itertuples()]
    if a.check:
        old = [re.sub(r"\s*\\\\\s*$", "", l) for l in Path(a.check).read_text().split("\n")
               if l.count("&") == 8 and "$" in l and not l.startswith("task")]
        assert [o.rstrip() for o in old] == [b.rstrip() for b in base], "the first nine columns differ from the released table"
    L = ["% generated by scripts/emit_named_pairs_with_families.py from erasure/named_pair_verdicts_full.csv and",
         "% erasure/family_weighted_repair_full.csv; do not edit by hand",
         r"\begin{adjustbox}{max width=\linewidth}", r"\begin{tabular}{llrrrrrllrl}", r"\toprule",
         r"\rowcolor{CompassLavender!32}",
         r" & & & \multicolumn{2}{c}{effect vs.\ null} & \multicolumn{3}{c}{repair contrast vs.\ null} & & "
         r"\multicolumn{2}{c}{one vote per family} \\",
         r"\cmidrule(lr){4-5}\cmidrule(lr){6-8}\cmidrule(lr){10-11}", r"\rowcolor{CompassLavender!32}",
         r"task & property & $n$ & mean & positive & mean & positive & Holm $p$ & named & positive & named \\",
         r"\midrule"]
    for r, b in zip(V.itertuples(), base):
        f = Fm.loc[(r.task, r.concept)]
        L.append(f"{b} & {int(f.pos_fam)}/{int(f.n_fam)} & {'yes' if bool(f.passes) else ''} \\\\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{adjustbox}", ""]
    out = ROOT / "erasure" / "named_pairs_full_families.tex"
    out.write_text("\n".join(L))
    print("wrote", out, "(first nine columns checked)" if a.check else "")


if __name__ == "__main__":
    main()
