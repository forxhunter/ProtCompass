"""Re-run agreement of the repair contrast: the 18 candidate pairs, first run on the local machine
(erasure/named_pairs -> named_pair_cells.csv), against the same pairs inside the full 60-pair grid
(named_pair_cells_full.csv): fluorescence, membrane vs soluble, PPI affinity, subcellular localisation and solubility
(composition, burial, contact order, shape) ran on the remote CPU server, remote homology's contact order, shape,
secondary structure and size started locally and finished there, and every other cell ran locally.

Per pair and encoder the two runs share the data, the splits, the heads and the seeds of the shams and nulls; they
differ in the BLAS build, the thread count and, for the remote tasks, the machine. The variance-matched null is
selected by a randomised swap search over principal directions whose variances can be nearly tied, so small
numerical differences can select a different subset. Reported per pair: the correlation of R_var over encoders, the
median absolute difference, the share of encoders whose sign agrees, the change in the panel mean, and whether the
naming verdict agrees.

  python grid_reproducibility.py [--latex]
"""
import os as _os  # release: repository root, override with the PROTCOMPASS_ROOT environment variable
PROTCOMPASS_ROOT = _os.environ.get("PROTCOMPASS_ROOT") or _os.path.abspath(
    _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "../.."))
import argparse
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path((PROTCOMPASS_ROOT + "/protcompass"))
REMOTE_TASKS = {"fluorescence", "membrane_soluble", "ppi_affinity"}
REMOTE_SOLUBILITY = {"amino-acid composition", "burial and packing", "contact order", "global shape"}
LABEL = {"membrane_soluble": "membrane vs soluble", "subcellular_localization": "localisation",
         "fluorescence": "fluorescence", "solubility": "solubility", "ppi_affinity": "PPI affinity",
         "go_mf": "GO-MF", "go_bp": "GO-BP", "stability": "stability", "ec_classification": "EC",
         "remote_homology": "remote homology"}
SHORT = {"amino-acid composition": "composition", "burial and packing": "burial", "secondary structure content":
         "secondary structure", "global shape": "global shape", "contact order": "contact order", "size": "size"}


REMOTE_TASKS |= {"subcellular_localization"}                          # moved to the remote when the local host overloaded
REMOTE_HOMOLOGY = {"contact order", "global shape", "secondary structure content", "size"}


def machine(task, concept):
    if task in REMOTE_TASKS or (task == "solubility" and concept in REMOTE_SOLUBILITY):
        return "remote"
    if task == "remote_homology" and concept in REMOTE_HOMOLOGY:
        return "local+remote"                                            # first six encoders local, the rest remote
    return "local"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--latex", action="store_true")
    a = ap.parse_args()
    A = pd.read_csv(ROOT / "erasure" / "named_pair_cells.csv")
    B = pd.read_csv(ROOT / "erasure" / "named_pair_cells_full.csv")
    VA = pd.read_csv(ROOT / "erasure" / "named_pair_verdicts.csv").set_index(["task", "concept"])
    VB = pd.read_csv(ROOT / "erasure" / "named_pair_verdicts_full.csv").set_index(["task", "concept"])
    m = A.merge(B, on=["task", "concept", "encoder"], suffixes=("_a", "_b"))
    rows = []
    for (t, c), g in m.groupby(["task", "concept"]):
        x, y = g.R_null_a.to_numpy(), g.R_null_b.to_numpy()
        rows.append(dict(task=t, concept=c, machine=machine(t, c), n=len(g),
                         r=float(np.corrcoef(x, y)[0, 1]) if len(g) > 2 else np.nan,
                         mad=float(np.median(np.abs(x - y))), sign_agree=float(np.mean(np.sign(x) == np.sign(y))),
                         mean_a=float(x.mean()), mean_b=float(y.mean()),
                         named_a=bool(VA.loc[(t, c), "passes_R_rule"]), named_b=bool(VB.loc[(t, c), "passes_R_rule"])))
    R = pd.DataFrame(rows).sort_values(["task", "concept"])
    R.to_csv(ROOT / "erasure" / "grid_reproducibility.csv", index=False)
    if a.latex:
        print("% generated by scripts/grid_reproducibility.py; do not edit by hand")
        print("\\begin{tabular}{llrrrrrl}")
        print("\\toprule")
        print("task & property & encoders & $r$ & median $|\\Delta R|$ & sign agrees & "
              "mean $R_{\\mathrm{var}}$, first $\\to$ re-run & named, first / re-run \\\\")
        print("\\midrule")
        for q in R.itertuples():
            print(f"{LABEL[q.task]} & {SHORT[q.concept]} & {q.n} & ${q.r:.2f}$ & ${q.mad:.4f}$ & "
                  f"{q.sign_agree:.0%} & ${q.mean_a:+.4f} \\to {q.mean_b:+.4f}$ & "
                  f"{'yes' if q.named_a else 'no'} / {'yes' if q.named_b else 'no'} \\\\".replace("%", "\\%"))
        print("\\bottomrule")
        print("\\end{tabular}")
        return
    pd.set_option("display.width", 220)
    print(R.round(4).to_string(index=False))
    for k, g in R.groupby("machine"):
        print(f"{k}: median r {g.r.median():.2f}, median |dR| {g.mad.median():.4f}, verdicts agree "
              f"{int((g.named_a == g.named_b).sum())} of {len(g)}")


if __name__ == "__main__":
    main()
