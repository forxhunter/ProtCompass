"""LaTeX tables of the symmetric probing rerun (scripts/symmetric_decide.py output) for both manuscripts.

  python symmetric_latex.py OUT_DIR [OUT_DIR ...]
Writes, in every OUT_DIR: symmetric_counts.tex (both splits, every floor rule), symmetric_selectivity.tex, and
symmetric_hypotheses.tex (the frozen topology-split hypotheses as decided).
"""
import os as _os  # release: repository root, override with the PROTCOMPASS_ROOT environment variable
PROTCOMPASS_ROOT = _os.environ.get("PROTCOMPASS_ROOT") or _os.path.abspath(
    _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "../.."))
import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path((PROTCOMPASS_ROOT + "/protcompass"))
SYM = ROOT / "symmetric"
RULE = {"admissible": "input-matched", "group": "released eligibility", "nbr4": "neighbourhood, $K=4$",
        "nbr8": "neighbourhood, $K=8$", "nbr16": "neighbourhood, $K=16$"}


def counts():
    rows = []
    for split in ("superfamily", "topology"):
        f = SYM / f"counts_{split}.csv"
        if not f.exists():
            continue
        K = pd.read_csv(f)
        K = K[(K.determined) & (K.subset == "all")]
        for rule in RULE:
            g = K[K.rule == rule].set_index("coordinates")
            if not len(g):
                continue
            c, s = g.loc[True], g.loc[False]
            rows.append(f"{split} & {RULE[rule]} & {int(c.cells)} & {int(c.point_below)} & {int(c.below)} & "
                        f"{int(c.unresolved)} & {int(c.above)} & {int(s.cells)} & {int(s.below)} & {int(s.above)} \\\\")
    head = ("split & floors & cells & point below & below & unresolved & above & cells & below & above \\\\")
    return ("% generated by scripts/symmetric_latex.py; do not edit by hand\n"
            "\\begin{tabular}{llrrrrrrrr}\n\\toprule\n"
            " & & \\multicolumn{5}{c}{coordinate encoders} & \\multicolumn{3}{c}{sequence-only encoders} \\\\\n"
            "\\cmidrule(lr){3-7}\\cmidrule(lr){8-10}\n" + head + "\n\\midrule\n" + "\n".join(rows)
            + "\n\\bottomrule\n\\end{tabular}\n")


def selectivity():
    S = pd.read_csv(SYM / "selectivity_superfamily.csv")
    S["group"] = S.coordinates.map({True: "coordinate", False: "sequence-only"})
    S["identity"] = S.residue_identity.map({True: "reads residue identity", False: "no residue identity"})
    rows = []
    for (g, i), d in S.groupby(["group", "identity"]):
        rows.append(f"{g} & {i} & {len(d)} & ${d.dssp3.median():.3f}$ & ${d.control.median():.3f}$ & "
                    f"${d.selectivity.median():+.3f}$ & {int((d.state == 'below').sum())} & "
                    f"{int((d.state == 'above').sum())} \\\\")
    return ("% generated by scripts/symmetric_latex.py; do not edit by hand\n"
            "\\begin{tabular}{llrrrrrr}\n\\toprule\n"
            "encoders & input & $n$ & DSSP-3 & control task & selectivity & below floor & above floor \\\\\n"
            "\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


def hypotheses():
    f = SYM / "hypotheses_topology.json"
    fz = SYM / "freeze_topology.json"
    if not f.exists() or not fz.exists():
        return None
    H, F = json.loads(f.read_text()), json.loads(fz.read_text())
    rows = [f"T1 & {F['hypotheses']['T1']} & {H['T1_below']} of {H['T1_cells']} ({H['T1_share_below']:.0%}) & "
            f"{'holds' if H['T1'] else 'fails'} \\\\",
            f"T2 & {F['hypotheses']['T2']} & {H['T2_seq_below']} of {H['T2_cells']} & {'holds' if H['T2'] else 'fails'} \\\\",
            "T3 & " + F['hypotheses']['T3'] + " & " + "; ".join(
                f"{ {'rsa': 'RSA', 'rsa_bins': 'RSA bins', 'bfactor': 'B-factor'}[p]}: {len(v)}"
                for p, v in sorted(H["T3_labels_with_encoder_above"].items(), key=lambda kv: ("rsa", "rsa_bins", "bfactor").index(kv[0])))
            + f" & {'holds' if H['T3'] else 'fails'} \\\\",
            f"T4 & {F['hypotheses']['T4']} & ${H['T4_delta']:+.3f}$ $[{H['T4_lo']:+.3f}, {H['T4_hi']:+.3f}]$ & "
            f"{'holds' if H['T4'] else 'fails'} \\\\"]
    rows = [r.replace("%", "\\%").replace("rsa_bins", "RSA bins").replace("rsa,", "RSA,").replace("bfactor", "B-factor")
            for r in rows]
    return ("% generated by scripts/symmetric_latex.py; do not edit by hand\n"
            "\\begin{tabular}{lp{7.2cm}p{3.2cm}l}\n\\toprule\n"
            "& hypothesis, as frozen & result & \\\\\n\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


def main():
    for d in sys.argv[1:]:
        d = Path(d)
        (d / "symmetric_counts.tex").write_text(counts())
        if (SYM / "selectivity_superfamily.csv").exists():
            (d / "symmetric_selectivity.tex").write_text(selectivity())
        h = hypotheses()
        if h:
            (d / "symmetric_hypotheses.tex").write_text(h)
        print("wrote", d)


if __name__ == "__main__":
    main()
