"""How much of a determined property does each encoder discard, as a graded number rather than a count.

The floor comparison is reported as a count of cells below the floor, which is stable under the descriptor
selection but says only which side of a line each encoder falls on. The empirical content the determinacy argument
does not predict is *how much* each encoder discarded, and it is reported here as a per-encoder score. It is
the mean gap to the floor over the informative determined probes, on the sign convention that a positive score
means information was lost:

    discard(e) = mean over probes p of [ floor(p, e) - score(e, p) ]

with the floor being the one the input audit assigns that encoder, so a sequence-only model is not charged for
failing to recover something only coordinates determine.

The question this then answers is whether the score is anything more than a restatement of width and pretraining.

  python discard_score.py [--markdown]
"""
import os as _os  # release: repository root, override with the PROTCOMPASS_ROOT environment variable
PROTCOMPASS_ROOT = _os.environ.get("PROTCOMPASS_ROOT") or _os.path.abspath(
    _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "../.."))
import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import spearmanr

ROOT = Path((PROTCOMPASS_ROOT + "/protcompass"))
sys.path.insert(0, str(ROOT / "scripts"))
from make_panels_original_style import DECLARED, DISP  # noqa: E402

UND = {"rsa", "rsa_bins", "bfactor", "architecture_label"}
TAUT = {"contact_density", "contact_order_len_resid"}


def meta():
    rows = []
    for d in sorted((ROOT / "extract" / "embeddings" / "stability").glob("*/meta.json")):
        if d.parent.name == "ref_composition":
            continue
        m = json.loads(d.read_text())
        w = np.load(d.parent / "train.npy", mmap_mode="r").shape[1]
        rows.append(dict(encoder=d.parent.name, params=int(m.get("n_parameters") or 0), dim=int(w),
                         pretrained=int(m.get("weights", "pretrained") == "pretrained")))
    return pd.DataFrame(rows).set_index("encoder")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--markdown", action="store_true")
    a = ap.parse_args()
    g = pd.read_csv(ROOT / "probing_results" / "gain_over_reference_by_probe.csv").set_index("source")
    probes = [p for p in pd.read_csv(ROOT / "probing_results" / "floor_vs_encoders.csv").probe
              if p in g.columns and p not in UND and p not in TAUT]
    # the released table stores encoder minus floor, so the discard score is its negative
    d = (-g[probes]).mean(axis=1).rename("discard").to_frame()
    d["n_probes"] = g[probes].notna().sum(axis=1)
    m = meta().reindex(d.index)
    d = d.join(m)
    d["class"] = [DECLARED.get(e, "struct") for e in d.index]
    d = d.sort_values("discard")
    d.round(4).to_csv(ROOT / "probing_results" / "discard_score.csv")

    ok = d[d.params > 0]
    r_dim = spearmanr(np.log(ok.dim), ok.discard)
    r_par = spearmanr(np.log(ok.params), ok.discard)
    coord = d[d["class"] != "seq"]
    r_dim_c = spearmanr(np.log(coord.dim), coord.discard)

    if a.markdown:
        print("<!-- generated by scripts/discard_score.py; do not edit by hand -->\n")
        print("| encoder | class | discard score | width | parameters |")
        print("|---|---|---|---|---|")
        for e, r in d.iterrows():
            print(f"| {DISP.get(e, e)} | {r['class']} | {r.discard:+.3f} | {int(r.dim)} | "
                  f"{int(r.params) if r.params else '--'} |")
        print(f"\nThe score is the mean of floor minus encoder over the {len(probes)} informative determined "
              f"probes, against the floor the input audit assigns that encoder, so positive means information "
              f"was lost. Over the panel it correlates with log width at $\\rho={r_dim.statistic:+.2f}$ and with "
              f"log parameters at $\\rho={r_par.statistic:+.2f}$.")
        return
    print(d[["class", "discard", "dim", "params", "pretrained"]].round(3).to_string())
    print(f"\n{len(probes)} informative determined probes: {', '.join(probes)}")
    print(f"discard vs log width      rho {r_dim.statistic:+.3f}  p {r_dim.pvalue:.1e}")
    print(f"discard vs log parameters rho {r_par.statistic:+.3f}  p {r_par.pvalue:.1e}")
    print(f"coordinate side only, vs log width rho {r_dim_c.statistic:+.3f}  p {r_dim_c.pvalue:.1e}")
    print(f"class means: " + ", ".join(f"{k} {v:+.3f}" for k, v in d.groupby('class').discard.mean().items()))


if __name__ == "__main__":
    main()
