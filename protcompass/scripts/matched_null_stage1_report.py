"""The released conditional effect of every pair the effect rule names, against the sham and the variance-matched null.

Reads the conditional arm of the released sweep re-run with the variance-matched null added
(scripts/erasure_v2.py --matched-null, erasure/parts_matched/), keeps the 33-encoder panel, and writes the table of
Appendix sec:appendix_matched_null. The composition reference sits in the embedding cache like an encoder and is
dropped here, as everywhere.

  python matched_null_stage1_report.py [--latex]
"""
import os as _os  # release: repository root, override with the PROTCOMPASS_ROOT environment variable
PROTCOMPASS_ROOT = _os.environ.get("PROTCOMPASS_ROOT") or _os.path.abspath(
    _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "../.."))
import argparse
import glob
import os
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import binomtest

sys.path.insert(0, str(Path(__file__).parent))
from family_weighted_demand import holm                                 # noqa: E402
from panel import only_panel                                            # noqa: E402

ROOT = Path((PROTCOMPASS_ROOT + "/protcompass"))
LABEL = {"membrane_soluble": "membrane vs soluble", "subcellular_localization": "subcellular localisation",
         "fluorescence": "fluorescence", "solubility": "solubility", "ppi_affinity": "PPI affinity",
         "go_mf": "GO-MF", "stability": "stability"}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--latex", action="store_true")
    a = ap.parse_args()
    fs = [f for f in glob.glob(str(ROOT / "erasure" / "parts_matched" / "erasure_v2_*.csv")) if os.path.getsize(f) > 50]
    d = pd.concat([pd.read_csv(f) for f in fs], ignore_index=True)
    d = d[d.arm == "conditional"].drop_duplicates(subset=["task", "encoder", "concept"], keep="last")
    d = only_panel(d)
    named = pd.read_csv(ROOT / "erasure" / "causal_demand_v2.csv")
    named = set(zip(named.task[named.demanded], named.concept[named.demanded]))
    rows = []
    for (t, c), g in d.groupby(["task", "concept"]):
        g = g[g.effect.notna() & g.effect_null.notna()]
        if len(g) < 5:
            continue
        rows.append(dict(task=t, concept=c, n=len(g), named=(t, c) in named,
                         eff_sham=g.effect.mean(), pos_sham=int((g.effect > 0).sum()),
                         p_sham=binomtest(int((g.effect > 0).sum()), len(g), 0.5).pvalue,
                         eff_null=g.effect_null.mean(), pos_null=int((g.effect_null > 0).sum()),
                         p_null=binomtest(int((g.effect_null > 0).sum()), len(g), 0.5).pvalue))
    R = pd.DataFrame(rows)
    R["p_null_holm"] = holm(R.p_null.to_numpy())
    R = R.sort_values("eff_null", ascending=False).reset_index(drop=True)
    R.to_csv(ROOT / "erasure" / "matched_null_stage1.csv", index=False)
    if a.latex:
        print("% generated by scripts/matched_null_stage1_report.py; do not edit by hand")
        print("\\begin{tabular}{llrrrrr}")
        print("\\toprule")
        print("task & property & $n$ & \\multicolumn{2}{c}{$\\Delta_{\\mathrm{sham}}$} & "
              "\\multicolumn{2}{c}{$\\Delta_{\\mathrm{var}}$} \\\\")
        print("\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}")
        print(" & & & mean & positive & mean & positive \\\\")
        print("\\midrule")
        for r in R.itertuples():
            star = "$^{\\ast}$" if r.named else ""
            print(f"{LABEL.get(r.task, r.task)}{star} & {r.concept} & {r.n} & ${r.eff_sham:+.4f}$ & {r.pos_sham} & "
                  f"${r.eff_null:+.4f}$ & {r.pos_null} \\\\")
        print("\\bottomrule")
        print("\\end{tabular}")
        return
    pd.set_option("display.width", 220)
    print(R.round(4).to_string(index=False))
    s = R[R.named]
    print(f"\nnamed pairs whose effect against the matched null clears a Holm-corrected sign test: "
          f"{int((s.p_null_holm < 0.05).sum())} of {len(s)}")


if __name__ == "__main__":
    main()
