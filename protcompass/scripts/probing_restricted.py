"""The floor comparison under the same restriction the downstream comparison gets.

The downstream claim is reported over all encoders and again over pretrained encoders of at least 100M parameters,
because the coordinate side is half randomly initialised and mostly small. The probing claim was reported only over
all encoders, and "233 of 245 coordinate cells fall below the floor" is then partly a
statement that small untrained geometric networks discard more than large pretrained language models do. The same
restriction is applied here.

  python probing_restricted.py [--markdown]
"""
import os as _os  # release: repository root, override with the PROTCOMPASS_ROOT environment variable
PROTCOMPASS_ROOT = _os.environ.get("PROTCOMPASS_ROOT") or _os.path.abspath(
    _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "../.."))
import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path((PROTCOMPASS_ROOT + "/protcompass"))
BY = ROOT / "probing_results" / "by_source"
sys.path.insert(0, str(ROOT / "scripts"))
from make_panels_original_style import DISP  # noqa: E402

SEQ_FLOORS = ["ref_length", "ref_position", "ref_aa", "ref_seq_window", "ref_seq_expert", "ref_seq_global"]
ALL_FLOORS = SEQ_FLOORS + ["ref_coords", "ref_backbone", "ref_global", "ref_pairhist"]
UND = {"rsa", "rsa_bins", "bfactor", "architecture_label"}
TAUT = {"contact_density", "contact_order_len_resid"}
LAB = {"phi_circular": "phi", "psi_circular": "psi", "local_curvature": "local curvature", "dssp_3": "DSSP-3",
       "dssp_8": "DSSP-8", "core_surface": "core / surface", "distance_bins": "CA distance bins",
       "contact_order_len_resid": "contact order", "radius_of_gyration_len_resid": "radius of gyration",
       "asphericity_len_resid": "asphericity", "contact_density": "contact density"}


def headline():
    """The same metric the released comparison uses: Pearson, then circular cosine, then balanced accuracy."""
    rows = []
    for f in sorted(BY.glob("*.csv")):
        d = pd.read_csv(f)
        d["headline"] = d["pearson"].fillna(d["circ_cos"] if "circ_cos" in d else np.nan).fillna(d["balanced_accuracy"])
        m = d.groupby(["source", "probe", "readout"], as_index=False).headline.mean()
        rows.append(m)
    d = pd.concat(rows, ignore_index=True)
    return d.loc[d.groupby(["source", "probe"]).headline.idxmax()].set_index(["source", "probe"]).headline


def meta():
    rows = []
    for d in sorted((ROOT / "extract" / "embeddings" / "stability").glob("*/meta.json")):
        if d.parent.name == "ref_composition":
            continue
        m = json.loads(d.read_text())
        rows.append(dict(encoder=d.parent.name, params=int(m.get("n_parameters") or 0),
                         pretrained=m.get("weights", "pretrained") == "pretrained"))
    return pd.DataFrame(rows).set_index("encoder")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--markdown", action="store_true")
    a = ap.parse_args()
    h = headline()
    audit = pd.read_csv(ROOT / "probing_results" / "floor_assignment.csv").rename(columns={"Unnamed: 0": "source"})
    uses = audit.set_index("source").uses_coordinates.astype(bool)
    m = meta()
    probes = [p for p in pd.read_csv(ROOT / "probing_results" / "floor_vs_encoders.csv").probe
              if p not in TAUT and p not in UND]
    coord = [e for e in m.index if uses.get(e, True)]
    big = [e for e in coord if m.loc[e, "pretrained"] and m.loc[e, "params"] >= 100e6]

    rows = []
    for probe in probes:
        floor = max(h.get((f, probe), np.nan) for f in ALL_FLOORS)
        if not np.isfinite(floor):
            continue
        def below(encs):
            v = [h.get((e, probe), np.nan) for e in encs]
            v = [x for x in v if np.isfinite(x)]
            return int(sum(x < floor for x in v)), len(v), (max(v) - floor if v else np.nan)
        b_all, n_all, gap_all = below(coord)
        b_big, n_big, gap_big = below(big)
        rows.append(dict(probe=LAB.get(probe, probe), floor=floor, below_all=b_all, n_all=n_all, gap_all=gap_all,
                         below_big=b_big, n_big=n_big, gap_big=gap_big))
    t = pd.DataFrame(rows)
    t.to_csv(ROOT / "probing_results" / "probing_restricted.csv", index=False)

    tot_all, tot_n = t.below_all.sum(), t.n_all.sum()
    tot_big, tot_nbig = t.below_big.sum(), t.n_big.sum()
    if a.markdown:
        print("<!-- generated by scripts/probing_restricted.py; do not edit by hand -->\n")
        print("| probe | floor | all coordinate encoders below | pretrained, $\\ge$100M below | best of those minus floor |")
        print("|---|---|---|---|---|")
        for r in t.itertuples():
            print(f"| {r.probe} | {r.floor:.3f} | {r.below_all} of {r.n_all} | {r.below_big} of {r.n_big} | "
                  f"{r.gap_big:+.3f} |")
        print(f"\n{tot_all} of {tot_n} cells over all coordinate encoders and {tot_big} of {tot_nbig} over the "
              f"pretrained encoders above 100M parameters: {', '.join(DISP.get(e, e) for e in big)}.")
        return
    print(t.round(3).to_string(index=False))
    print(f"\nall coordinate encoders: {tot_all} of {tot_n} cells below floor")
    print(f"pretrained >= 100M ({', '.join(big)}): {tot_big} of {tot_nbig}")


if __name__ == "__main__":
    main()
