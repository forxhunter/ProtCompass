"""Shuffled-3Di control: LaTeX table from downstream_deltas_shuf.csv (and probing_deltas_shuf.csv when present).

Writes ab_modality/table_shuf3di.tex (and table_shuf3di_probing.tex), and table_shuf3di_merged.tex, the compact
version the paper prints. ab_latex.py is imported for the labels only.
"""
import os as _os  # release: repository root, override with the PROTCOMPASS_ROOT environment variable
PROTCOMPASS_ROOT = _os.environ.get("PROTCOMPASS_ROOT") or _os.path.abspath(
    _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "../../.."))
import sys
from pathlib import Path

import pandas as pd

AB = Path((PROTCOMPASS_ROOT + "/protcompass/extract/ab_modality"))
sys.path.insert(0, str(AB))
from ab_latex import GROUP, METRIC, PROBE, TASK                          # noqa: E402


def ci(d, lo, hi):
    mark = "$^{+}$" if lo > 0 else "$^{-}$" if hi < 0 else ""
    return f"{d:+.3f} [{lo:+.3f}, {hi:+.3f}]{mark}"


def downstream():
    D = pd.read_csv(AB / "downstream_deltas_shuf.csv")
    out = ["% generated by extract/ab_modality/ab_shuf_latex.py from downstream_deltas_shuf.csv",
           "\\begin{table}[t]", "\\centering", "\\small",
           "\\caption{Shuffled-3Di control for SaProt on the downstream tasks. Full: real 3Di token at each residue; "
           "shuffled: the protein's own 3Di string permuted over positions (same letters and composition, wrong "
           "residue alignment); \\texttt{\\#}: every 3Di token masked. $S$ is the released protocol (linear or MLP-2 "
           "readout chosen on validation, mean of three seeds). $\\Delta_A = S(\\text{full}) - S(\\text{shuffled})$, "
           "$\\Delta_B = S(\\text{shuffled}) - S(\\text{\\#})$, with 95\\% paired bootstrap intervals over test "
           "proteins (test pairs for PPI affinity), 2,000 draws. $^{+}$: interval above zero; $^{-}$: below zero.}",
           "\\label{tab:saprot_shuffled_3di}",
           "\\resizebox{\\linewidth}{!}{%",
           "\\begin{tabular}{llccccc}", "\\toprule",
           "Task & Metric & full & shuffled & \\texttt{\\#} & $\\Delta_A$ [95\\% CI] & $\\Delta_B$ [95\\% CI] \\\\",
           "\\midrule"]
    for g, gname in GROUP.items():
        tasks = [t for t in TASK if t in set(D.task) and D[D.task == t].group.iloc[0] == g]
        if not tasks:
            continue
        out.append(f"\\multicolumn{{7}}{{l}}{{\\emph{{{gname}}}}} \\\\")
        for t in tasks:
            x = D[D.task == t].iloc[0]
            out.append(f"{TASK[t]} & {METRIC[x.metric]} & {x.S_saprot:.3f} & {x.S_shuf3di:.3f} & {x.S_seqonly:.3f} & "
                       f"{ci(x.delta_A, x.lo_A, x.hi_A)} & {ci(x.delta_B, x.lo_B, x.hi_B)} \\\\")
    out += ["\\bottomrule", "\\end{tabular}}", "\\end{table}"]
    (AB / "table_shuf3di.tex").write_text("\n".join(out) + "\n")


def probing():
    D = pd.read_csv(AB / "probing_deltas_shuf.csv")
    out = ["% generated by extract/ab_modality/ab_shuf_latex.py from probing_deltas_shuf.csv",
           "\\begin{table}[t]", "\\centering", "\\small",
           "\\caption{Shuffled-3Di control for SaProt on the structural probes (superfamily split, symmetric "
           "protocol). $\\Delta_A = S(\\text{full}) - S(\\text{shuffled})$, $\\Delta_B = S(\\text{shuffled}) - "
           "S(\\text{\\#})$, with 95\\% protein-level paired bootstrap intervals (2,000 draws); readout family chosen on "
           "validation for each source.}",
           "\\label{tab:saprot_shuffled_3di_probing}",
           "\\resizebox{\\linewidth}{!}{%",
           "\\begin{tabular}{lccccc}", "\\toprule",
           "Probe & full & shuffled & \\texttt{\\#} & $\\Delta_A$ [95\\% CI] & $\\Delta_B$ [95\\% CI] \\\\", "\\midrule"]
    for det, label in ((True, "Determined by the backbone"), (False, "Not determined by the backbone")):
        out.append(f"\\multicolumn{{6}}{{l}}{{\\emph{{{label}}}}} \\\\")
        for p in [p for p in PROBE if p in set(D.probe) and bool(D[D.probe == p].determined.iloc[0]) == det]:
            x = D[D.probe == p].iloc[0]
            out.append(f"{PROBE[p]} & {x.S_saprot:.3f} & {x.S_shuf3di:.3f} & {x.S_seqonly:.3f} & "
                       f"{ci(x.delta_A, x.lo_A, x.hi_A)} & {ci(x.delta_B, x.lo_B, x.hi_B)} \\\\")
    out += ["\\bottomrule", "\\end{tabular}}", "\\end{table}"]
    (AB / "table_shuf3di_probing.tex").write_text("\n".join(out) + "\n")


def mark(d, lo, hi):
    return f"{d:+.3f}" + ("$^{+}$" if lo > 0 else "$^{-}$" if hi < 0 else "\\phantom{$^{+}$}")


def merged():
    """One compact table for the paper: downstream tasks and probes side by side, differences with their interval sign
    only. The two tables above, with the intervals, are released."""
    D = pd.read_csv(AB / "downstream_deltas_shuf.csv")
    P = pd.read_csv(AB / "probing_deltas_shuf.csv")
    head = ["\\toprule", " & full & shuf. & \\texttt{\\#} & $\\Delta_A$ & $\\Delta_B$ \\\\", "\\midrule"]
    left = ["\\begin{tabular}[t]{@{}lrrrrr@{}}"] + [h.replace(" & full", "Task & full", 1) if h.startswith(" &") else h for h in head]
    for g, gname in GROUP.items():
        for t in [t for t in TASK if t in set(D.task) and D[D.task == t].group.iloc[0] == g]:
            x = D[D.task == t].iloc[0]
            left.append(f"{TASK[t]} & {x.S_saprot:.3f} & {x.S_shuf3di:.3f} & {x.S_seqonly:.3f} & "
                        f"{mark(x.delta_A, x.lo_A, x.hi_A)} & {mark(x.delta_B, x.lo_B, x.hi_B)} \\\\")
    left += ["\\bottomrule", "\\end{tabular}"]
    right = ["\\begin{tabular}[t]{@{}lrrrrr@{}}"] + [h.replace(" & full", "Probe & full", 1) if h.startswith(" &") else h for h in head]
    for det in (True, False):
        if not det:
            right.append("\\midrule")
        for q in [q for q in PROBE if q in set(P.probe) and bool(P[P.probe == q].determined.iloc[0]) == det]:
            x = P[P.probe == q].iloc[0]
            right.append(f"{PROBE[q]} & {x.S_saprot:.3f} & {x.S_shuf3di:.3f} & {x.S_seqonly:.3f} & "
                         f"{mark(x.delta_A, x.lo_A, x.hi_A)} & {mark(x.delta_B, x.lo_B, x.hi_B)} \\\\")
    right += ["\\bottomrule", "\\end{tabular}"]
    out = ["% generated by extract/ab_modality/ab_shuf_latex.py from downstream_deltas_shuf.csv and probing_deltas_shuf.csv",
           "\\begin{table}[!htbp]", "\\centering", "\\scriptsize", "\\setlength{\\tabcolsep}{3pt}",
           "\\caption{Shuffled-3Di control for SaProt on the ten downstream tasks (left) and the fifteen probes (right; "
           "below the rule, the four labels the backbone does not determine). Full: the real 3Di token at each residue; "
           "shuf.: the protein's own 3Di string permuted over positions (same letters and composition, wrong residue "
           "alignment); \\texttt{\\#}: every 3Di token masked. Scores use the released protocol with the readout chosen "
           "on validation. $\\Delta_A$ = full $-$ shuf., $\\Delta_B$ = shuf. $-$ \\texttt{\\#}; $^{+}$ / $^{-}$: the "
           "95\\% paired bootstrap interval over test proteins (2,000 draws) lies above / below zero. The intervals are "
           "released (\\texttt{extract/ab\\_modality/table\\_shuf3di.tex}, \\texttt{table\\_shuf3di\\_probing.tex}).}",
           "\\label{tab:saprot_shuffled_3di}", "\\label{tab:saprot_shuffled_3di_probing}",
           ] + left + ["\\hfill"] + right + ["\\end{table}"]
    (AB / "table_shuf3di_merged.tex").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    if (AB / "downstream_deltas_shuf.csv").exists():
        downstream()
    if (AB / "probing_deltas_shuf.csv").exists():
        probing()
    if (AB / "downstream_deltas_shuf.csv").exists() and (AB / "probing_deltas_shuf.csv").exists():
        merged()
