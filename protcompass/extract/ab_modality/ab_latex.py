"""Modality ablation: LaTeX tables from downstream_deltas.csv and probing_deltas.csv / probing_floor_cells.csv.

Writes ab_modality/table_downstream_deltas.tex and ab_modality/table_probing_deltas.tex.
"""
import os as _os  # release: repository root, override with the PROTCOMPASS_ROOT environment variable
PROTCOMPASS_ROOT = _os.environ.get("PROTCOMPASS_ROOT") or _os.path.abspath(
    _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "../../.."))
from pathlib import Path

import pandas as pd

AB = Path((PROTCOMPASS_ROOT + "/protcompass/extract/ab_modality"))
TASK = {"ec_classification": "EC number", "go_mf": "GO-MF", "go_bp": "GO-BP", "remote_homology": "Remote homology",
        "subcellular_localization": "Localisation", "membrane_soluble": "Membrane vs soluble",
        "stability": "Stability", "fluorescence": "Fluorescence", "solubility": "Solubility", "ppi_affinity": "PPI affinity"}
METRIC = {"spearman": "Spearman", "AUROC": "AUROC", "accuracy": "Acc.", "Fmax": "$F_{\\max}$"}
GROUP = {"experimental": "Experimental structures (PDB)", "predicted (AFDB)": "Predicted structures (AlphaFold DB)",
         "predicted (ESMFold)": "Predicted structures (ESMFold)"}
PROBE = {"phi_circular": "$\\phi$ (circular)", "psi_circular": "$\\psi$ (circular)", "local_curvature": "Local curvature",
         "dssp_3": "DSSP-3", "dssp_8": "DSSP-8", "core_surface": "Core vs surface", "contact_density": "Contact density",
         "distance_bins": "Distance bins", "contact_order_len_resid": "Contact order",
         "radius_of_gyration_len_resid": "Radius of gyration", "asphericity_len_resid": "Asphericity", "rsa": "RSA",
         "rsa_bins": "RSA bins", "bfactor": "B-factor", "architecture_label": "CATH architecture"}


def ci(d, lo, hi, state_pos, state_neg, st):
    mark = "$^{+}$" if st == state_pos else "$^{-}$" if st == state_neg else ""
    return f"{d:+.3f} [{lo:+.3f}, {hi:+.3f}]{mark}"


def downstream():
    D = pd.read_csv(AB / "downstream_deltas.csv")
    W = D.pivot(index="task", columns="model")
    out = ["% generated by extract/ab_modality/ab_latex.py from downstream_deltas.csv",
           "\\begin{table}[t]", "\\centering", "\\small",
           "\\caption{Within-model modality ablation on the downstream tasks. $S$ is the released protocol "
           "(linear or MLP-2 readout chosen on validation, mean of three seeds). $\\Delta = S(\\text{full}) - "
           "S(\\text{sequence only})$ with a 95\\% paired bootstrap interval over test proteins (test pairs for PPI "
           "affinity), 2,000 draws. $^{+}$: interval above zero; $^{-}$: interval below zero.}",
           "\\label{tab:modality_ablation_downstream}",
           "\\resizebox{\\linewidth}{!}{%",
           "\\begin{tabular}{llccrccr}", "\\toprule",
           " & & \\multicolumn{3}{c}{ESM3} & \\multicolumn{3}{c}{SaProt} \\\\",
           "\\cmidrule(lr){3-5}\\cmidrule(lr){6-8}",
           "Task & Metric & full & seq.\\ only & $\\Delta$ [95\\% CI] & full & seq.\\ only & $\\Delta$ [95\\% CI] \\\\",
           "\\midrule"]
    for g, gname in GROUP.items():
        tasks = [t for t in TASK if t in D.task.values and D.set_index("task").group.get(t) is not None
                 and (D[D.task == t].group.iloc[0] == g)]
        if not tasks:
            continue
        out.append(f"\\multicolumn{{8}}{{l}}{{\\emph{{{gname}}}}} \\\\")
        for t in tasks:
            r = {m: D[(D.task == t) & (D.model == m)].iloc[0] for m in ("esm3", "saprot")}
            cells = []
            for m in ("esm3", "saprot"):
                x = r[m]
                cells += [f"{x.S_full:.3f}", f"{x.S_seqonly:.3f}",
                          ci(x.delta, x.lo, x.hi, "structure adds", "structure costs", x.state)]
            out.append(f"{TASK[t]} & {METRIC[r['esm3'].metric]} & " + " & ".join(cells) + " \\\\")
    out += ["\\bottomrule", "\\end{tabular}}", "\\end{table}"]
    (AB / "table_downstream_deltas.tex").write_text("\n".join(out) + "\n")


def probing():
    D = pd.read_csv(AB / "probing_deltas.csv")
    F = pd.read_csv(AB / "probing_floor_cells.csv")
    F = F[F.source.isin(["esm3_seqonly", "saprot_seqonly"])].set_index(["source", "probe"])
    sym = {"above": "$\\uparrow$", "below": "$\\downarrow$", "unresolved": "$\\circ$"}
    out = ["% generated by extract/ab_modality/ab_latex.py from probing_deltas.csv and probing_floor_cells.csv",
           "\\begin{table}[t]", "\\centering", "\\small",
           "\\caption{Within-model modality ablation on the structural probes (superfamily split, symmetric protocol). "
           "$\\Delta = S(\\text{full}) - S(\\text{sequence only})$ with a 95\\% protein-level paired bootstrap interval "
           "(2,000 draws); readout family chosen on validation for each source. Floor: the sequence-only source "
           "against its input-matched floor (best of the six sequence floors, chosen on validation); "
           "$\\uparrow$ above, $\\downarrow$ below, $\\circ$ unresolved at 95\\%.}",
           "\\label{tab:modality_ablation_probing}",
           "\\resizebox{\\linewidth}{!}{%",
           "\\begin{tabular}{lcccc}", "\\toprule",
           " & \\multicolumn{2}{c}{ESM3} & \\multicolumn{2}{c}{SaProt} \\\\",
           "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}",
           "Probe & $\\Delta$ [95\\% CI] & seq.\\ only vs floor & $\\Delta$ [95\\% CI] & seq.\\ only vs floor \\\\",
           "\\midrule"]
    for det, label in ((True, "Determined by the backbone"), (False, "Not determined by the backbone")):
        out.append(f"\\multicolumn{{5}}{{l}}{{\\emph{{{label}}}}} \\\\")
        for p in [p for p in PROBE if p in D.probe.values and D[D.probe == p].determined.iloc[0] == det]:
            cells = []
            for m, s in (("esm3", "esm3_seqonly"), ("saprot", "saprot_seqonly")):
                x = D[(D.probe == p) & (D.model == m)].iloc[0]
                f = F.loc[(s, p)]
                cells += [ci(x.delta, x.lo, x.hi, "structure adds", "structure costs", x.state),
                          f"{f.gap:+.3f} {sym[f.state]}"]
            out.append(f"{PROBE[p]} & " + " & ".join(cells) + " \\\\")
    out += ["\\bottomrule", "\\end{tabular}}", "\\end{table}"]
    (AB / "table_probing_deltas.tex").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    if (AB / "downstream_deltas.csv").exists():
        downstream()
    if (AB / "probing_deltas.csv").exists():
        probing()
